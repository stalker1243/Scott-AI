using Avalonia.Controls;
using ScottAI.Avalonia.Views;
using Xunit;

namespace ScottAI.Avalonia.Tests;

/// <summary>
/// Полоса прокрутки не должна ложиться на текст.
///
/// В теме Fluent полоса не занимает место в разметке — она рисуется ПОВЕРХ
/// содержимого. В ленте чата пузыри с сообщениями прижаты к правому краю, и
/// полоса проходила ровно по последним буквам: в свёрнутом виде тонкой чертой,
/// а стоило подвести мышь — разворачивалась вместе со стрелками на концах и
/// накрывала символы. Пожаловался на это пользователь, прислав снимок чата.
///
/// Лечится отступом: содержимое отодвигается от края на ширину полосы. Число
/// маленькое и выглядит необязательным — такие правки первыми исчезают при
/// перекройке разметки, поэтому и проверяются.
///
/// Проверяется построенный контрол, а не текст разметки: так в проверку
/// попадает ровно то значение, с которым лента выйдет на экран.
/// </summary>
[Collection("avalonia")]
public class ScrollOverlapTests
{
    /// <summary>
    /// Ширина развёрнутой полосы Fluent. Меньший отступ оставит стрелки поверх
    /// текста — то есть починит вид ровно наполовину.
    /// </summary>
    private const double ШиринаПолосы = 12;

    [Fact]
    public void Лента_сообщений_отодвинута_от_полосы()
    {
        var чат = new ChatView();

        var лента = чат.FindControl<ScrollViewer>("Scroller");

        Assert.True(лента is not null, "в ChatView не нашлась лента сообщений");

        var справа = лента!.Padding.Right;

        Assert.True(справа >= ШиринаПолосы,
            $"отступ справа {справа} — полоса шириной {ШиринаПолосы} накроет последние буквы");
    }
}
