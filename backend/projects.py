"""
Проекты, над которыми человек работает.

Список сам по себе бесполезен — такой можно завести в блокноте. Смысл
появляется, когда Scott им пользуется, и пользуется он двумя способами.

ПЕРВЫЙ: «открой проект Scott» открывает папку. Не «папку, которую вы когда-то
назвали», а именно ту, где лежит работа, — и не приходится помнить путь.

ВТОРОЙ, менее очевидный: выбранный проект Scott держит в уме. Человек,
работающий над программой на C#, спрашивает «как здесь сделать асинхронно» — и
ответ про C# полезнее ответа вообще. Раньше это приходилось повторять в каждом
вопросе.

ЧТО ЗДЕСЬ ВАЖНО

Проект — не задача и не напоминание: он живёт месяцами, и «завершённых»
состояний у него нет. Удаление проекта не трогает папку на диске: Scott
перестаёт о нём знать, но работа остаётся на месте. Обратное было бы
катастрофой при первой же опечатке.

В разговор уходит только текущий проект, и только он один: перечислять модели
все проекты человека значит платить за это в каждом вопросе.
"""

from __future__ import annotations

import json
import os
import time
import uuid
from pathlib import Path
from typing import Dict, List, Optional

STORE_PATH = Path(__file__).resolve().parent / "data" / "projects.json"

MAX_NAME = 80
MAX_STACK = 80
MAX_NOTE = 200

# Сколько проектов помнить. Больше — это уже не «над чем я работаю», а архив.
MAX_TOTAL = 50


def _load() -> List[Dict]:
    try:
        if STORE_PATH.exists():
            данные = json.loads(STORE_PATH.read_text(encoding="utf-8"))
            if isinstance(данные, list):
                return [п for п in данные if isinstance(п, dict) and п.get("name")]
    except Exception:
        # Испорченный файл не повод падать при старте: Scott просто не знает о
        # проектах, а работать продолжает.
        pass
    return []


def _save(проекты: List[Dict]) -> None:
    STORE_PATH.parent.mkdir(parents=True, exist_ok=True)
    STORE_PATH.write_text(json.dumps(проекты, ensure_ascii=False, indent=2), encoding="utf-8")


def all_projects() -> List[Dict]:
    """
    Все проекты. Текущий — первым, остальные по свежести.

    Текущий наверху не ради красоты: к нему обращаются чаще всего, и искать его
    глазами в общем списке человек не должен.
    """
    проекты = _load()

    for проект in проекты:
        # Папка могла быть удалена или переехать. Сказать об этом честно лучше,
        # чем молча не открыть её по просьбе.
        путь = проект.get("path", "")
        проект["exists"] = bool(путь) and os.path.isdir(путь)

    return sorted(проекты,
                  key=lambda п: (not п.get("current"), -п.get("created", 0)))


def current() -> Optional[Dict]:
    """Проект, над которым человек работает сейчас."""
    for проект in _load():
        if проект.get("current"):
            return проект
    return None


def add(name: str, path: str = "", stack: str = "", note: str = "") -> Dict:
    """Завести проект."""
    имя = (name or "").strip()[:MAX_NAME]
    if not имя:
        return {"success": False, "error": "У проекта должно быть название"}

    путь = (path or "").strip()
    if путь and not os.path.isdir(путь):
        # Не отказ: папку могли ещё не создать, а проект уже есть. Но сказать
        # об этом стоит сразу, а не при первой попытке открыть.
        предупреждение = "Такой папки нет — проект заведён, но открыть его не получится"
    else:
        предупреждение = ""

    проекты = _load()

    for проект in проекты:
        if проект.get("name", "").strip().lower() == имя.lower():
            return {"success": False, "error": "Проект с таким названием уже есть"}

    проект = {
        "id": uuid.uuid4().hex[:12],
        "name": имя,
        "path": путь,
        "stack": (stack or "").strip()[:MAX_STACK],
        "note": (note or "").strip()[:MAX_NOTE],
        "created": time.time(),
        # Первый заведённый сразу становится текущим: человек, добавивший один
        # проект, уж точно работает над ним.
        "current": not any(п.get("current") for п in проекты),
    }

    проекты.append(проект)

    if len(проекты) > MAX_TOTAL:
        проекты = sorted(проекты, key=lambda п: п.get("created", 0))[-MAX_TOTAL:]

    _save(проекты)

    ответ = {"success": True, "project": проект}
    if предупреждение:
        ответ["note"] = предупреждение
    return ответ


def remove(project_id: str) -> Dict:
    """
    Забыть проект.

    Папка на диске не трогается: Scott перестаёт о нём знать, работа остаётся
    на месте. Обратное было бы катастрофой при первой же опечатке.
    """
    проекты = _load()
    осталось = [п for п in проекты if п.get("id") != project_id]

    if len(осталось) == len(проекты):
        return {"success": False, "error": "Такого проекта нет"}

    # Если убрали текущий, текущим становится самый свежий из оставшихся:
    # без этого Scott перестал бы держать в уме хоть что-нибудь.
    if осталось and not any(п.get("current") for п in осталось):
        самый_свежий = max(осталось, key=lambda п: п.get("created", 0))
        самый_свежий["current"] = True

    _save(осталось)
    return {"success": True}


def set_current(project_id: str) -> Dict:
    """Переключиться на другой проект."""
    проекты = _load()
    нашёлся = False

    for проект in проекты:
        свой = проект.get("id") == project_id
        проект["current"] = свой
        нашёлся = нашёлся or свой

    if not нашёлся:
        return {"success": False, "error": "Такого проекта нет"}

    _save(проекты)
    return {"success": True}


# Насколько похожими должны быть слова, чтобы счесть их одним названием.
#
# То же значение, что и при поиске приложений: там оно подобрано на живых
# названиях из меню «Пуск».
MIN_SIMILARITY = 0.72


def _на_слух(слово: str) -> str:
    """
    Слово в том виде, в каком оно звучит.

    Перевода в латиницу мало: русское «к» пишется как «k», английское — как
    «c», и «скотт» превращается в «skott» против «scottai». Одной буквы хватает,
    чтобы сходство упало ниже порога, — проверено, вышло 0.67 при нужных 0.72.

    Поэтому буквы, звучащие одинаково, сводятся к одной, а удвоения
    схлопываются: «skott» и «scottai» становятся «skot» и «skotai».
    """
    try:
        from . import app_resolver
    except ImportError:
        import app_resolver

    звучит = app_resolver.transliterate(слово)

    замены = (("ck", "k"), ("ph", "f"), ("c", "k"), ("q", "k"), ("y", "i"), ("z", "s"))
    for что, на_что in замены:
        звучит = звучит.replace(что, на_что)

    # Удвоения на слух неразличимы: «Scott» и «Skot» звучат одинаково.
    сжатое = []
    for буква in звучит:
        if not сжатое or сжатое[-1] != буква:
            сжатое.append(буква)

    return "".join(сжатое)


def _похожесть(a: str, b: str) -> float:
    """Насколько похожи два слова на слух."""
    from difflib import SequenceMatcher

    первое = _на_слух(a)
    второе = _на_слух(b)

    if первое == второе:
        return 1.0

    return SequenceMatcher(None, первое, второе).ratio()


def find(query: str) -> Optional[Dict]:
    """
    Найти проект по названию — для просьбы «открой проект такой-то».

    Три захода: точное совпадение, вхождение и — для голоса — сравнение по
    словам с поправкой на произношение.

    Последнее здесь не роскошь. Человек говорит «открой проект скотт», Whisper
    пишет это кириллицей, а проект называется ScottAI: прямое сравнение не
    находит ничего, и даже перевод в латиницу даёт «skott» против «scottai» —
    русское «к» пишется как «k», английское как «c». Поймано на живой проверке:
    проект был заведён, а Scott отвечал «не знаю такого».
    """
    искомое = (query or "").strip().lower()
    if not искомое:
        return None

    проекты = _load()

    for проект in проекты:
        if проект.get("name", "").lower() == искомое:
            return проект

    for проект in проекты:
        if искомое in проект.get("name", "").lower():
            return проект

    # По словам: «скотт» должно находить «ScottAI Remake», а не сравниваться со
    # всей строкой целиком — длинное название иначе всегда проигрывает.
    лучший, лучшая_оценка = None, 0.0

    for проект in проекты:
        for слово in проект.get("name", "").lower().split():
            оценка = _похожесть(искомое, слово)
            if оценка > лучшая_оценка:
                лучший, лучшая_оценка = проект, оценка

    return лучший if лучшая_оценка >= MIN_SIMILARITY else None


def prompt_addition() -> str:
    """
    Текущий проект — словами для модели.

    Только он один: перечислять все проекты человека значит платить за это в
    каждом вопросе, а помогает обычно тот, за которым он сидит сейчас.
    """
    проект = current()
    if not проект:
        return ""

    части = [f"Сейчас человек работает над проектом «{проект['name']}»"]

    if проект.get("stack"):
        части.append(f"на {проект['stack']}")

    строка = " ".join(части) + "."

    if проект.get("note"):
        строка += f" {проект['note']}"

    return строка + " Учитывай это, когда вопрос касается его работы."
