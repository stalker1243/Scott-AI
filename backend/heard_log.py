"""
Что Scott услышал и что из этого вышло.

ЗАЧЕМ ЭТО ЕСТЬ. Голосом Scott умеет заметно меньше, чем в чате, — и это первое,
что замечает человек, попробовав обе двери. Но разбор у них ОДИН И ТОТ ЖЕ:
`_process_command_impl` не знает, откуда пришла фраза. Значит дело не в
возможностях, а в тексте, который до разбора доходит: с микрофона он приходит
искажённым, и Scott либо не узнаёт своё имя, либо получает команду, которой
человек не произносил.

Проверить это было нечем. Распознанное печаталось в вывод, который читает
лаунчер, и нигде не сохранялось: за вчерашний сеанс 29 фраз дошли до
распознавания, а до разбора команды — 10, и почему пропали остальные
девятнадцать, узнать неоткуда. Спрашивать человека «а что именно вы сказали»
бессмысленно: он сказал то, что хотел, вопрос в том, что услышал Scott.

Теперь каждая услышанная фраза записывается вместе с исходом: узнал ли Scott
имя, осталась ли команда, выполнил ли он её. По такому журналу за один вечер
видно, какие варианты имени теряются и какие команды не разбираются, — вместо
догадок появляется список.

ЧЕГО ЗДЕСЬ НЕТ. Звука. Пишется только текст: хранить записи голоса человека без
его ведома — не то, что помощник должен делать молча. Журнал лежит рядом с
остальными, в папке, которая не уезжает в репозиторий, и ограничен по длине.
"""

from __future__ import annotations

import json
import time
from pathlib import Path
from typing import Dict, List, Optional

LOG_PATH = Path(__file__).resolve().parent / "logs" / "heard.jsonl"

# Сколько последних фраз хранить.
#
# Двухсот хватает на несколько вечеров обычной работы — этого достаточно, чтобы
# увидеть повторяющуюся беду, а не единичную оговорку. Файл при этом остаётся
# размером в десятки килобайт.
MAX_ENTRIES = 200


def record(text: str, outcome: str, command: str = "",
           seconds: Optional[float] = None) -> None:
    """
    Записать услышанное.

    `outcome` — что с фразой стало: «выполнена», «мимо» (имени не было),
    «имя без команды», «ошибка». `command` — то, что осталось после снятия
    имени: по нему видно, верно ли оно снялось.

    Не бросает исключений: сбой записи в журнал не должен мешать Scott
    слушать.
    """
    try:
        записи = read()

        записи.append({
            "at": round(time.time(), 2),
            "text": (text or "")[:300],
            "outcome": outcome,
            "command": (command or "")[:300],
            "seconds": seconds,
        })

        LOG_PATH.parent.mkdir(parents=True, exist_ok=True)
        LOG_PATH.write_text(
            "\n".join(json.dumps(з, ensure_ascii=False) for з in записи[-MAX_ENTRIES:]),
            encoding="utf-8")
    except Exception:
        pass


def read(limit: int = MAX_ENTRIES) -> List[Dict]:
    """Последние услышанные фразы, от старых к новым."""
    try:
        if not LOG_PATH.exists():
            return []

        записи = []
        for строка in LOG_PATH.read_text(encoding="utf-8", errors="ignore").splitlines():
            строка = строка.strip()
            if not строка:
                continue
            try:
                записи.append(json.loads(строка))
            except Exception:
                # Одна испорченная строка не повод потерять остальные.
                continue

        return записи[-limit:]
    except Exception:
        return []


def clear() -> None:
    """Забыть услышанное. Человек вправе это стереть — это его речь."""
    try:
        if LOG_PATH.exists():
            LOG_PATH.unlink()
    except Exception:
        pass


def summary() -> Dict:
    """
    Сводка: сколько фраз и чем кончились.

    Главное число здесь — доля прошедших мимо. Если Scott слышит половину
    сказанного, но узнаёт своё имя в трети случаев, лечить надо имя, а не
    разбор команд.
    """
    записи = read()
    итоги: Dict[str, int] = {}

    for з in записи:
        исход = з.get("outcome", "?")
        итоги[исход] = итоги.get(исход, 0) + 1

    return {"total": len(записи), "outcomes": итоги}
