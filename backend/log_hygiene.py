"""
Чужие библиотеки в журнале: почему они там молчат.

ПОЧЕМУ ЭТО НЕ КОСМЕТИКА. На уровне DEBUG urllib3 печатает полный адрес каждого
запроса, а токен Telegram-бота стоит прямо в адресе:

    GET /bot<ТОКЕН>/getUpdates

То есть ключ от Scott ложился в файл на диске открытым текстом, раз в тридцать
секунд. За одиннадцать дней журнал вырос до шести с половиной мегабайт, и
токен встречался в нём сотни раз. Токен, попавший в такой файл, надо считать
утёкшим: файл копируется вместе с папкой, уезжает в отчёт об ошибке, попадает
в архив с логами.

ВТОРАЯ ПРИЧИНА. Журнал заводился ради traceback при падениях, а состоял из
отладочной переписки httpcore и urllib3, в которой настоящую ошибку было не
найти. Приглушив чужое, мы возвращаем ему смысл.

Свои модули это не трогает: Scott продолжает писать в журнал всё, что писал.
"""

import logging
from typing import Iterable

# Кто именно шумит. Список закрытый, а не «все чужие»: приглушить всё разом
# значило бы однажды не увидеть сообщение библиотеки о настоящей беде.
NOISY = (
    "urllib3",       # печатает адреса запросов вместе с токенами
    "httpcore",
    "httpx",
    "groq",
    "openai",
    "anthropic",
    "faster_whisper",
    "asyncio",
    "PIL",
    "matplotlib",
)


def quiet_third_party(names: Iterable[str] = NOISY,
                      level: int = logging.WARNING) -> None:
    """Оставить от чужих библиотек только предупреждения и ошибки."""
    for имя in names:
        logging.getLogger(имя).setLevel(level)
