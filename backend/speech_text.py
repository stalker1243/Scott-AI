"""
Подготовка текста к произнесению.

Silero говорит по-русски и только по-русски. Всё остальное он выбрасывает, и
последствия хуже, чем кажется:

* **Числа пропадают целиком.** «Памяти занято 48 процентов» звучит как «память
  занята процентов» — фраза сохраняет форму, но теряет смысл, и заметить это
  можно только на слух.
* **Латиница проглатывается.** «Открыл через APP_MAP: блокнот → notepad.exe»
  превращается в «Открыл через блокнот».
* **Если русских букв не остаётся вовсе, синтез падает** с ValueError. Так
  ответ «CPU: 34.5%, RAM: 48.1%» каждый раз уходил на облачный Edge TTS —
  медленнее и с обязательным интернетом, причём молча.

Поэтому текст переводится в то, что можно произнести: эмодзи и оформление
убираются, аббревиатуры получают русские названия, числа разворачиваются
словами, а спорные ударения проставляются явно.
"""

