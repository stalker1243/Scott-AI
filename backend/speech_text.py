def transliterate(word: str) -> str:
    """Грубая транслитерация: лучше приблизительное звучание, чем тишина."""
    return "".join(TRANSLIT.get(char.lower(), char) for char in word)


def russify_latin(text: str) -> str:
    """
    Заменить известные сокращения и слова, остальную латиницу —
    транслитерировать побуквенно.

    Порядок важен: сперва слова, которые Scott произносит постоянно
    («Google Chrome» → «гугл хром»), и только потом всё прочее побуквенно.
    Наоборот не выйдет — побуквенный разбор съест слово целиком, и подставлять
    будет уже нечего.
    """
    for pattern, replacement in ABBREVIATIONS:
        text = re.sub(pattern, replacement, text, flags=re.IGNORECASE)

    def по_словарю(match: re.Match) -> str:
        слово = match.group(0)
        звучание = PRONUNCIATION.get(слово.lower())
        return звучание if звучание else слово

    text = re.sub(r"[A-Za-z]{2,}", по_словарю, text)

    def побуквенно(match: re.Match) -> str:
        return transliterate(match.group(0))

    return re.sub(r"[A-Za-z]{2,}", побуквенно, text)


# ==================== Числа ====================

UNITS = [
    (r"%", " процентов"),
    (r"\bГБ\b", " гигабайт"),
    (r"\bМБ\b", " мегабайт"),
    (r"\bКБ\b", " килобайт"),
    (r"\bмс\b", " миллисекунд"),
    (r"\bГц\b", " герц"),
]


def _number_to_words(raw: str) -> str:
    if not HAS_NUM2WORDS:
        return raw
    try:
        text = raw.replace(",", ".")
        value = float(text)
        if value.is_integer():
            return num2words(int(value), lang="ru")
        return num2words(round(value, 2), lang="ru")
    except (ValueError, OverflowError):
        return raw


# Как читаются одиночные латинские буквы.
#
# Их в ответах немного, но они важные: «диск C» без этого звучит как «диск» —
# Silero выбрасывает одинокую латиницу молча, и фраза теряет главное слово.
# Читаются по-русски, как их и называют вслух: диск цэ, а не диск си.
SINGLE_LETTERS = {
    "a": "а", "b": "бэ", "c": "цэ", "d": "дэ", "e": "е", "f": "эф",
    "g": "гэ", "h": "аш", "i": "и", "j": "йот", "k": "ка", "l": "эль",
    "m": "эм", "n": "эн", "o": "о", "p": "пэ", "q": "ку", "r": "эр",
    "s": "эс", "t": "тэ", "u": "у", "v": "вэ", "w": "дубль-вэ",
    "x": "икс", "y": "игрек", "z": "зет",
}


def read_single_letters(text: str) -> str:
    """Одиночные латинские буквы — русскими названиями."""
    def заменить(match: re.Match) -> str:
        return SINGLE_LETTERS.get(match.group(0).lower(), match.group(0))

    return re.sub(r"(?<![A-Za-zА-Яа-я])[A-Za-z](?![A-Za-zА-Яа-я])", заменить, text)


def split_compound_numbers(text: str) -> str:
    """
    Развести числа, склеенные знаками: время и номера версий.

    «Напомню в 14:30» произносилось как «четырнадцать двоеточие тридцать» —
    точнее, двоеточие Silero проглатывал, и выходило «четырнадцатьтридцать».
    «Версия 2.0.5» и вовсе теряла середину: получалось «два пять».

    Делается до разворота чисел словами: тому нужны отдельные числа, а не
    склейка из трёх.
    """
    def развести_время(match: re.Match) -> str:
        # Ведущий ноль в минутах отделяется: «9:05» иначе читается как «девять
        # пять», и на слух это девять часов пять минут или пять часов — не
        # разобрать.
        части = []
        for часть in match.groups():
            if часть is None:
                continue
            части.append(f"0 {часть[1:]}" if len(часть) == 2 and часть[0] == "0"
                         else часть)

        return " ".join(части)

    # Время: 14:30 → 14 30. Секунды, если они есть, тоже отделяются.
    text = re.sub(r"\b(\d{1,2}):(\d{2})(?::(\d{2}))?\b", развести_время, text)

    # Версии: 2.0.5 → 2 0 5. Две части («версия 2.0») не трогаем — их
    # разворот числом читает как «два и ноль десятых», что для версии верно
    # звучит хуже, но переписывать тут нечего: точка одна, и она законная.
    text = re.sub(r"\b(\d+)\.(\d+)\.(\d+)\b", r"\1 \2 \3", text)

    return text


def expand_numbers(text: str) -> str:
    """
    Развернуть числа словами.

    Без этого числа просто исчезают из речи: Silero их не проговаривает, и
    «Запущено 285 процессов» звучит как «запущено процессов».
    """
    for pattern, replacement in UNITS:
        text = re.sub(pattern, replacement, text)

    return re.sub(r"\d+(?:[.,]\d+)?", lambda m: _number_to_words(m.group(0)), text)


# ==================== Ударения ====================
#
# Silero расставляет ударения сам, но на части слов ошибается. Знак «+» перед
# гласной он понимает как явное указание — им и пользуемся. Список стоит
# пополнять по мере того, как ошибки слышны: угадать их заранее нельзя.

ACCENTS = {
    "процессор": "проц+ессор",
    "процессора": "проц+ессора",
    "процессоров": "проц+ессоров",
    "процессы": "проц+ессы",
    "процессов": "проц+ессов",
    "запущено": "зап+ущено",
    "включено": "включен+о",
    "громкость": "гр+омкость",
    "громче": "гр+омче",
    "тише": "т+ише",
    "яркость": "+яркость",
    "яркости": "+яркости",
    "звонит": "звон+ит",
    "включит": "включ+ит",
    "красивее": "крас+ивее",
    "одновременно": "одноврем+енно",
    "обеспечение": "обесп+ечение",
    "средства": "ср+едства",
    "каталог": "катал+ог",
    "гигабайт": "гигаб+айт",
    "видеокарта": "видеок+арта",
    "накопитель": "накоп+итель",
    "диалог": "диал+ог",
    "диалоги": "диал+оги",
    "токен": "т+окен",
    "бэкенд": "б+экенд",
    "синтез": "с+интез",
}


def put_accents(text: str) -> str:
    """Проставить ударения в словах, где Silero ошибается."""
    def replace(match: re.Match) -> str:
        word = match.group(0)
        marked = ACCENTS.get(word.lower())
        if not marked:
            return word
        # Сохраняем заглавную букву, если слово начинало предложение.
        if word.isupper():
            return marked.upper()
        if word[0].isupper():
            initial = 1 if marked.startswith('+') else 0
            return marked[:initial] + marked[initial].upper() + marked[initial + 1:]
        return marked

    return re.sub(r"(?<![А-Яа-яЁё+])[А-Яа-яЁё]+", replace, text)


# ==================== Всё вместе ====================

def has_speakable_content(text: str) -> bool:
    """
    Есть ли в тексте хоть одна русская буква.

    Silero требует именно этого: на строке без кириллицы он бросает ValueError,
    а вызывающий код принимает это за сбой движка и уходит на облачный синтез.
    """
    return bool(re.search(r"[А-Яа-яЁё]", text))


def prepare_for_speech(text: str, accents: bool = True) -> str:
    """
    Привести текст к виду, который Silero сможет произнести осмысленно.

    Порядок шагов не случаен: сначала снимается оформление (иначе значки
    попадут в транслитерацию), затем латиница становится русской (среди неё
    бывают единицы измерения), и только потом разворачиваются числа — им нужны
    уже русские слова рядом. Ударения ставятся последними, по готовому тексту.
    """
    if not text:
        return ""

    text = strip_code_blocks(text)
    text = shorten_paths(text)
    text = strip_decoration(text)
    text = russify_latin(text)

    # Одиночные буквы — до разворота чисел: «диск C» иначе теряет букву совсем,
    # а «14:30» без этого шага склеивается в одно длинное число.
    text = read_single_letters(text)
    text = split_compound_numbers(text)

    text = expand_numbers(text)
    if accents:
        text = put_accents(text)

    # Схлопываем пробелы, оставшиеся от вырезанных значков.
    text = re.sub(r"\s+", " ", text).strip()
    # Двоеточие в конце фразы звучит как оборванная мысль.
    text = re.sub(r"[:;]\s*$", "", text)

    return text


# ==================== Сколько зачитывать вслух ====================

# Сколько предложений Scott произносит из длинного ответа.
#
# Замер, с которого это началось: ответ ИИ на «что такое фотосинтез» — 583
# знака, и Scott читал его 43 секунды. Всё это время микрофон приглушён, чтобы
# он не услышал сам себя, — то есть перебить его нельзя даже словом. Человек,
# задавший короткий вопрос голосом, ждал сорок три секунды монолога.
#
# Два предложения — примерно десять секунд речи. Этого хватает, чтобы ответить
# по существу; остальное человек прочитает в чате, если захочет.
SPOKEN_SENTENCES = 2

# Верхняя граница на случай, когда предложения сами по себе длинные: одно
# предложение на четыреста знаков читается полминуты.
SPOKEN_CHARS = 320

# Что дописать, когда ответ обрезан. Без этого человек решит, что Scott
# оборвался на полуслове или не знает продолжения.
SPOKEN_TAIL = "Подробнее — в чате."


def shorten_for_speech(
    text: str,
    sentences: int = SPOKEN_SENTENCES,
    chars: int = SPOKEN_CHARS,
) -> str:
    """
    Оставить от ответа то, что стоит произнести вслух.

    Обрезается по границе предложения, а не по числу знаков: фраза, оборванная
    на середине слова, звучит как поломка. Если и первое предложение длиннее
    предела, оно всё равно произносится целиком — лучше долго, чем бессмысленно.

    Короткие ответы возвращаются как есть: «Готово» обрезать нечего, и
    приписка про чат к нему не нужна.
    """
    прибранный = (text or "").strip()
    if not прибранный:
        return ""

    куски = _split_sentences(прибранный)

    if len(куски) <= sentences and len(прибранный) <= chars:
        return прибранный

    отобранные = []
    длина = 0
    for кусок in куски[:sentences]:
        # Первое предложение берём всегда, даже если оно длиннее предела:
        # иначе вслух не прозвучит ничего.
        if отобранные and длина + len(кусок) > chars:
            break
        отобранные.append(кусок)
        длина += len(кусок) + 1

    произносимое = " ".join(отобранные).strip()
    if not произносимое:
        return прибранный

    if len(отобранные) < len(куски):
        произносимое = f"{произносимое} {SPOKEN_TAIL}"

    return произносимое


# Сколько знаков должно быть в куске, который уходит на синтез отдельно.
#
# Резать на каждое предложение нельзя: «Готово.» и «Открыл.» дали бы два файла и
# рваную речь с паузой посередине. Шестьдесят знаков — примерно две секунды
# звучания, этого хватает, чтобы следующий кусок успел синтезироваться, пока
# играет текущий.
SPEAK_CHUNK_CHARS = 60


def split_for_speech(text: str, min_chars: int = SPEAK_CHUNK_CHARS) -> list:
    """
    Разделить ответ на куски, которые синтезируются по отдельности.

    ЗАЧЕМ. Длинный ответ синтезируется целиком, и только потом начинает
    звучать: замеры показывают до 2,4 секунды тишины после команды, прежде чем
    Scott скажет первое слово. Человек в это время не знает, услышали его или
    нет. Если же синтезировать по частям, первое слово звучит через время
    одного предложения, а остальное доготавливается, пока играет начало.

    Первое предложение отделяется всегда, даже короткое: смысл именно в том,
    чтобы начать говорить раньше. Дальше куски склеиваются до `min_chars` —
    иначе речь распадётся на обрывки с паузами.

    Короткий ответ возвращается одним куском: «Готово» делить нечего, и оно
    почти всегда уже лежит в кэше озвученных реплик.
    """
    прибранный = (text or "").strip()
    if not прибранный:
        return []

    предложения = _split_sentences(прибранный)
    if len(предложения) <= 1:
        return [прибранный]

    куски = [предложения[0]]

    for предложение in предложения[1:]:
        if len(куски[-1]) < min_chars and len(куски) > 1:
            куски[-1] = f"{куски[-1]} {предложение}"
        else:
            куски.append(предложение)

    # Последний кусок мог остаться совсем коротким — «Да.» в конце звучит
    # обрывком, поэтому он прилипает к предыдущему.
    if len(куски) > 1 and len(куски[-1]) < 20:
        # Сначала снимаем, потом приклеиваем: pop() внутри f-строки сдвигает
        # индексы до того, как до них дойдёт дело.
        хвост = куски.pop()
        куски[-1] = f"{куски[-1]} {хвост}"

    return куски


def _split_sentences(text: str) -> list:
    """
    Разбить текст на предложения.

    Точка после сокращения или числа концом предложения не считается: иначе
    «версия 1.2» и «т. е.» разрывают фразу посередине.
    """
    куски = re.split(r'(?<=[.!?…])\s+(?=[А-ЯЁA-Z«])', text)
    return [к.strip() for к in куски if к.strip()]
