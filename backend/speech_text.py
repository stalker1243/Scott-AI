"""
Подготовка текста к произнесению.

Silero говорит по-русски и только по-русски. Всё остальное он выбрасывает, и
последствия хуже, чем кажется:

* **Числа пропадают целиком.** «Памяти занято 48 процентов» звучит как «память
  занята процентов» — фраза сохраняет форму, но теряет смысл, и заметить это
  можно только на слух.
* **Латиница проглатывается.** «Открыл через APP_MAP: блокнот → notepad.exe»
  превращается в «Открыл через блокнот».
* **Если русских букв не остаётся вовсе, синтез падает** с ValueError. Так
  ответ «CPU: 34.5%, RAM: 48.1%» каждый раз уходил на облачный Edge TTS —
  медленнее и с обязательным интернетом, причём молча.

Поэтому текст переводится в то, что можно произнести: эмодзи и оформление
убираются, аббревиатуры получают русские названия, числа разворачиваются
словами, а спорные ударения проставляются явно.
"""

from __future__ import annotations

import re
import unicodedata
from typing import List

try:
    from num2words import num2words
    HAS_NUM2WORDS = True
except ImportError:  # pragma: no cover - зависимость есть в requirements
    HAS_NUM2WORDS = False


# ==================== Оформление, которое не произносят ====================
#
# Эмодзи Silero и так игнорирует, но убрать их нужно по другой причине: если
# кроме них в строке ничего нет, синтез падает. Плюс лишние символы сбивают
# расстановку пауз.

DECORATIVE = {
    "→": " ",
    "←": " ",
    "↔": " ",
    "•": " ",
    "·": " ",
    "—": " — ",
    "–": " ",
    "«": "",
    "»": "",
    "“": "",
    "”": "",
    "*": " ",
    "#": " ",
    "`": " ",
    "_": " ",
    "|": " ",
    "\\": " ",
    "/": " ",
}


# Блок кода в ответе: ```язык … ```. Читать его вслух бессмысленно — Silero
# честно произносит «решётка инклюд стдио точка аш», и слушать это невозможно.
CODE_BLOCK = re.compile(r"```[^\n]*\n.*?```", re.DOTALL)


def strip_code_blocks(text: str) -> str:
    """
    Заменить блоки кода упоминанием о них.

    Код Scott показывает в чате, где его можно прочитать и скопировать
    кнопкой; вслух достаточно сказать, что он там появился.
    """
    return CODE_BLOCK.sub(" Код показан в чате. ", text)


# Полный путь к файлу: «C:\Users\User\ScottAI\code\scott_program.c». Вслух это
# превращалось в «цэ двоеточие усерс скйнет скоттаи коде скотт програм цэ» —
# набор звуков, из которого ничего не понять. Путь целиком человек видит в
# чате, произносить достаточно имя файла.
FILE_PATH = re.compile(
    r"(?:[A-Za-z]:)?(?:[\\/][^\\/\s]+){2,}"
)


def shorten_paths(text: str) -> str:
    """Заменить полные пути к файлам их именами."""

    def replace(match: re.Match) -> str:
        return re.split(r"[\\/]", match.group(0))[-1]

    return FILE_PATH.sub(replace, text)


def strip_decoration(text: str) -> str:
    """Убрать эмодзи, значки и разметку — всё, что не читается вслух."""
    for source, replacement in DECORATIVE.items():
        text = text.replace(source, replacement)

    kept: List[str] = []
    for char in text:
        category = unicodedata.category(char)
        # So — символы вроде ✅🚀, Cs — суррогаты, Cf — служебные метки
        # (например, вариационные селекторы у эмодзи).
        if category in ("So", "Cs", "Cf"):
            continue
        kept.append(char)

    return "".join(kept)


# ==================== Латиница ====================
#
# Порядок важен: длинные сокращения заменяются раньше коротких, иначе «CPU»
# внутри «CPU-Z» разберётся неправильно. Список намеренно короткий — только то,
# что Scott произносит сам; остальное транслитерируется побуквенно.

ABBREVIATIONS = [
    (r"\bCPU\b", "процессор"),
    (r"\bGPU\b", "видеокарта"),
    (r"\bRAM\b", "оперативная память"),
    (r"\bSSD\b", "накопитель"),
    (r"\bHDD\b", "жёсткий диск"),
    (r"\bOK\b", "хорошо"),
    (r"\bPowerShell\b", "пауэршелл"),
    (r"\bGitHub\b", "гитхаб"),
    (r"\bYouTube\b", "ютуб"),
    (r"\bWindows\b", "виндоус"),
    (r"\bLinux\b", "линукс"),
    (r"\bScott\b", "Скотт"),
    (r"\bAI\b", "искусственный интеллект"),
]

TRANSLIT = {
    "a": "а", "b": "б", "c": "к", "d": "д", "e": "е", "f": "ф", "g": "г",
    "h": "х", "i": "и", "j": "дж", "k": "к", "l": "л", "m": "м", "n": "н",
    "o": "о", "p": "п", "q": "к", "r": "р", "s": "с", "t": "т", "u": "у",
    "v": "в", "w": "в", "x": "кс", "y": "й", "z": "з",
}


def transliterate(word: str) -> str:
    """Грубая транслитерация: лучше приблизительное звучание, чем тишина."""
    return "".join(TRANSLIT.get(char.lower(), char) for char in word)


def russify_latin(text: str) -> str:
    """Заменить известные сокращения, остальную латиницу — транслитерировать."""
    for pattern, replacement in ABBREVIATIONS:
        text = re.sub(pattern, replacement, text, flags=re.IGNORECASE)

    def replace(match: re.Match) -> str:
        return transliterate(match.group(0))

    return re.sub(r"[A-Za-z]{2,}", replace, text)


# ==================== Числа ====================

UNITS = [
    (r"%", " процентов"),
    (r"\bГБ\b", " гигабайт"),
    (r"\bМБ\b", " мегабайт"),
    (r"\bКБ\b", " килобайт"),
    (r"\bмс\b", " миллисекунд"),
    (r"\bГц\b", " герц"),
]


def _number_to_words(raw: str) -> str:
    if not HAS_NUM2WORDS:
        return raw
    try:
        text = raw.replace(",", ".")
        value = float(text)
        if value.is_integer():
            return num2words(int(value), lang="ru")
        return num2words(round(value, 2), lang="ru")
    except (ValueError, OverflowError):
        return raw


def expand_numbers(text: str) -> str:
    """
    Развернуть числа словами.

    Без этого числа просто исчезают из речи: Silero их не проговаривает, и
    «Запущено 285 процессов» звучит как «запущено процессов».
    """
    for pattern, replacement in UNITS:
        text = re.sub(pattern, replacement, text)

    return re.sub(r"\d+(?:[.,]\d+)?", lambda m: _number_to_words(m.group(0)), text)


# ==================== Ударения ====================
#
# Silero расставляет ударения сам, но на части слов ошибается. Знак «+» перед
# гласной он понимает как явное указание — им и пользуемся. Список стоит
# пополнять по мере того, как ошибки слышны: угадать их заранее нельзя.

ACCENTS = {
    "процессор": "проц+ессор",
    "процессора": "проц+ессора",
    "процессоров": "проц+ессоров",
    "процессы": "проц+ессы",
    "процессов": "проц+ессов",
    "запущено": "запущен+о",
    "включено": "включен+о",
    "громкость": "гр+омкость",
    "громче": "гр+омче",
    "тише": "т+ише",
    "яркость": "ярк+ость",
    "звонит": "звон+ит",
    "включит": "включ+ит",
    "красивее": "крас+ивее",
    "одновременно": "одноврем+енно",
    "обеспечение": "обеспеч+ение",
    "средства": "ср+едства",
    "каталог": "катал+ог",
    "гигабайт": "гигаб+айт",
    "видеокарта": "видеок+арта",
    "накопитель": "накоп+итель",
}


def put_accents(text: str) -> str:
    """Проставить ударения в словах, где Silero ошибается."""
    def replace(match: re.Match) -> str:
        word = match.group(0)
        marked = ACCENTS.get(word.lower())
        if not marked:
            return word
        # Сохраняем заглавную букву, если слово начинало предложение.
        return marked.capitalize() if word[0].isupper() else marked

    return re.sub(r"[А-Яа-яЁё]+", replace, text)


# ==================== Всё вместе ====================

def has_speakable_content(text: str) -> bool:
    """
    Есть ли в тексте хоть одна русская буква.

    Silero требует именно этого: на строке без кириллицы он бросает ValueError,
    а вызывающий код принимает это за сбой движка и уходит на облачный синтез.
    """
    return bool(re.search(r"[А-Яа-яЁё]", text))


def prepare_for_speech(text: str, accents: bool = True) -> str:
    """
    Привести текст к виду, который Silero сможет произнести осмысленно.

    Порядок шагов не случаен: сначала снимается оформление (иначе значки
    попадут в транслитерацию), затем латиница становится русской (среди неё
    бывают единицы измерения), и только потом разворачиваются числа — им нужны
    уже русские слова рядом. Ударения ставятся последними, по готовому тексту.
    """
    if not text:
        return ""

    text = strip_code_blocks(text)
    text = shorten_paths(text)
    text = strip_decoration(text)
    text = russify_latin(text)
    text = expand_numbers(text)
    if accents:
        text = put_accents(text)

    # Схлопываем пробелы, оставшиеся от вырезанных значков.
    text = re.sub(r"\s+", " ", text).strip()
    # Двоеточие в конце фразы звучит как оборванная мысль.
    text = re.sub(r"[:;]\s*$", "", text)

    return text
