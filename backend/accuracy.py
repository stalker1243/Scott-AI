"""
Точность разбора: одно число вместо ощущения.

ЗАЧЕМ. Все дыры, найденные за сентябрь, нашлись СЛУЧАЙНО — споткнувшись о них
в работе. «Выключи компьютер» не работало никогда: Scott искал программу с
таким названием и честно сообщал, что не нашёл. «Убавь яркость» доходило до
исполнителя с параметром «убавь». «Открой Google Chrome» голосом превращалось в
«открой кукол хром». Каждую заметили, когда она уже мешала жить.

Набор фраз с ожидаемым разбором даёт то, чего не хватало: число. Стало 92%
вместо 88% — правка помогла; стало 84% — сломала что-то соседнее, и видно, что
именно.

ЧТО ЭТО НЕ ПРОВЕРЯЕТ. Выполнение. Здесь только понимание: во что превращается
фраза до того, как что-то произойдёт. Ошибка понимания — самая дорогая: Scott
уверенно делает не то, о чём просили, и человеку кажется, что он сломался.

СЛУХ ПРОВЕРЯЕТСЯ ОТДЕЛЬНО. Фразы здесь текстовые. Проверка распознавания —
`accuracy_voice`: те же фразы, произнесённые синтезом и пропущенные через
настоящий слух. Она медленная и требует моделей, поэтому живёт отдельно.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Dict, List, Optional

PHRASES_PATH = Path(__file__).resolve().parent / "tests" / "data" / "phrases.json"


def load_phrases(path: Optional[Path] = None) -> List[Dict]:
    """Прочитать набор. Пустой список — если файла нет: набор пополняем руками."""
    файл = path or PHRASES_PATH

    try:
        данные = json.loads(файл.read_text(encoding="utf-8"))
        return данные.get("фразы", [])
    except Exception:
        return []


def check(understanding, engines: Dict, phrases: Optional[List[Dict]] = None) -> Dict:
    """
    Прогнать набор через разбор и посчитать попадания.

    `engines` — те же движки, что работают у живого Scott: подменять их здесь
    нечем и незачем, проверяется именно то, что人 услышит в работе.

    Возвращает сводку и список промахов. Промахи важнее числа: по ним видно, что
    именно чинить, а число показывает, стало лучше или хуже.
    """
    набор = phrases if phrases is not None else load_phrases()

    попаданий = 0
    промахи: List[Dict] = []

    for запись in набор:
        фраза = запись.get("фраза", "")
        if not фраза:
            continue

        try:
            решение = understanding.understand(фраза, **engines)
        except Exception as e:
            промахи.append({
                "фраза": фраза,
                "ожидалось": запись.get("вид"),
                "вышло": f"ошибка разбора: {e}",
            })
            continue

        вышло_вид = решение.kind
        вышло_действие = решение.action or ""
        вышло_параметр = getattr(решение.parsed, "main_param", "") if решение.parsed else ""

        ожидание_вид = запись.get("вид")
        ожидание_действие = запись.get("действие")
        ожидание_параметр = запись.get("параметр")

        верно = вышло_вид == ожидание_вид

        if верно and ожидание_действие:
            верно = вышло_действие == ожидание_действие

        if верно and ожидание_параметр:
            верно = вышло_параметр == ожидание_параметр

        if верно:
            попаданий += 1
        else:
            промахи.append({
                "фраза": фраза,
                "ожидалось": _описать(ожидание_вид, ожидание_действие, ожидание_параметр),
                "вышло": _описать(вышло_вид, вышло_действие, вышло_параметр),
                "почему": решение.reason,
            })

    всего = len([з for з in набор if з.get("фраза")])

    return {
        "всего": всего,
        "попаданий": попаданий,
        "промахов": len(промахи),
        "точность": round(попаданий / всего * 100, 1) if всего else 0.0,
        "промахи": промахи,
    }


def _описать(вид: Optional[str], действие: str = "", параметр: str = "") -> str:
    """Короткая запись разбора — чтобы промахи читались строкой, а не словарём."""
    части = [вид or "?"]

    if действие:
        части.append(действие)
    if параметр:
        части.append(f"«{параметр}»")

    return " / ".join(части)


def report(итог: Dict) -> str:
    """Отчёт словами — для вывода в консоль и для раздела диагностики."""
    строки = [
        f"Точность разбора: {итог['точность']}% "
        f"({итог['попаданий']} из {итог['всего']})",
    ]

    if итог["промахи"]:
        строки.append("")
        строки.append("Не понято:")
        for промах in итог["промахи"]:
            строки.append(f"  «{промах['фраза']}»")
            строки.append(f"      ожидалось: {промах['ожидалось']}")
            строки.append(f"      вышло:     {промах['вышло']}")

    return "\n".join(строки)
