"""
Отложенные команды: сделать не сейчас, а когда придёт время.

«Напомни через час позвонить маме» Scott умел и раньше — и в назначенный час
произносил эти слова вслух. Отличие здесь одно, но принципиальное: «через час
запусти рендер» он не напомнит, а ВЫПОЛНИТ.

В службе напоминаний вид «command» был объявлен с самого начала — и не
использовался никем: что бы в нём ни лежало, при срабатывании оно
проговаривалось. Заготовка, о которой все забыли.

ЗАЧЕМ ЭТО НУЖНО СЕЙЧАС. Само по себе полезно: «выключи компьютер через два
часа», «запусти сборку в семь утра». Но главное — это основание для другого:
команда, отложенная до условия, ничем не отличается от команды, присланной с
телефона и ждущей возвращения человека домой. Очередь одна и та же; меняется
только то, откуда команда пришла и чего она ждёт.

ЧТО ЗДЕСЬ ВАЖНО

Отложенное исполняется без человека. Значит список того, что можно отложить,
уже, чем список того, что Scott умеет вообще: выключение компьютера через два
часа — да, а «удали папку» без спроса — нет. Спросить в момент срабатывания
некому.
"""

from __future__ import annotations

from typing import Dict, Optional

# Что НЕЛЬЗЯ откладывать.
#
# Не потому, что Scott этого не умеет, а потому, что в назначенный час рядом
# может никого не быть: подтвердить или остановить будет некому. Для таких
# действий отложенное исполнение — способ узнать о беде постфактум.
FORBIDDEN = {
    "delete_file",
    "run_script",
    "powershell",
    "shell",
}

# Слова, по которым видно, что человек просит СДЕЛАТЬ, а не напомнить.
#
# «Напомни выключить компьютер» — это напоминание: сказать вслух. «Выключи
# компьютер через час» — команда. Разница только в глаголе, и спутать их значит
# либо промолчать вместо дела, либо выключить компьютер вместо напоминания.
REMIND_MARKERS = (
    "напомни",
    "напомню",
    "напомнить",
    "напоминание",
    "не забыть",
    "не забудь",
)


def is_reminder(text: str) -> bool:
    """
    Это просьба напомнить, а не сделать?

    Проверяется наличие глагола «напомни» и ему подобных. Без них фраза с
    временем — отложенная команда: «выключи компьютер через час».
    """
    низ = (text or "").lower()
    return any(маркер in низ for маркер in REMIND_MARKERS)


def can_defer(command_type: str) -> bool:
    """
    Можно ли отложить такую команду.

    Отказ здесь — не придирка: в назначенный час рядом может никого не быть, и
    спросить «точно удалить?» будет некому.
    """
    return command_type not in FORBIDDEN


def refusal(command_type: str) -> str:
    """Почему эту команду нельзя отложить — словами для человека."""
    return ("Такое я не откладываю: когда придёт время, рядом может никого не "
            "быть, а подтвердить будет некому. Скажите, когда будете на месте.")
