"""
Расписание протоколов: когда Scott запускает их сам.

ЗАЧЕМ. Протокол — это одна фраза вместо четырёх, но фразу всё равно надо
сказать. С расписанием он превращается в настоящую автоматизацию: «по будням в
девять — Работа», «в одиннадцать вечера — Конец дня». Человек не просит, а
приходит к готовому.

КАК ЗАПИСЫВАЕТСЯ. Строкой, теми же словами, какими человек сказал бы это вслух:

    «каждый день в 9:00»
    «по будням в 09:30»
    «пн, ср, пт в 18:00»
    «по выходным в 11:00»

Разбор снисходителен к форме — «9:00» и «09:00», «пн-пт» и «по будням», — но
при неудаче честно отказывается: расписание, понятое неверно, хуже
отсутствующего, потому что срабатывает не тогда, когда ждут.

ПРОПУЩЕННОЕ НЕ ДОГОНЯЕТСЯ. Если компьютер был выключен в девять утра, протокол
«Работа» не должен запускаться в семь вечера, когда его включили: человек ждал
его утром, а вечером он уже помеха. Срабатывание засчитывается, только если с
назначенного времени прошло немного.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from datetime import datetime, timedelta
from typing import List, Optional

# Сколько времени у протокола есть на то, чтобы сработать.
#
# Scott мог быть занят, спать вместе с компьютером или запускаться. Полчаса —
# столько, в течение которых утренний протокол ещё уместен. Позже он уже
# мешает: человек давно начал день сам.
GRACE_MINUTES = 30

ДНИ = {
    "пн": 0, "понедельник": 0, "вт": 1, "вторник": 1, "ср": 2, "среда": 2,
    "чт": 3, "четверг": 3, "пт": 4, "пятница": 4, "сб": 5, "суббота": 5,
    "вс": 6, "воскресенье": 6,
}

БУДНИ = [0, 1, 2, 3, 4]
ВЫХОДНЫЕ = [5, 6]

ИМЕНА_ДНЕЙ = ["пн", "вт", "ср", "чт", "пт", "сб", "вс"]

_ВРЕМЯ = re.compile(r"\b(\d{1,2})[:.](\d{2})\b")
_ЧАС = re.compile(r"\bв\s+(\d{1,2})\b")


@dataclass
class Schedule:
    """
    Когда запускать: время суток и дни недели.

    Пустой список дней означает «каждый день» — так человек и говорит чаще
    всего, и отдельного признака для этого заводить незачем.
    """

    hour: int = 9
    minute: int = 0
    days: List[int] = field(default_factory=list)
    enabled: bool = True

    def __post_init__(self) -> None:
        self.hour = max(0, min(23, int(self.hour)))
        self.minute = max(0, min(59, int(self.minute)))
        self.days = sorted({int(д) for д in (self.days or []) if 0 <= int(д) <= 6})

    # ---- когда ----

    def matches_day(self, when: datetime) -> bool:
        return not self.days or when.weekday() in self.days

    def due(self, now: datetime, last_run: Optional[datetime]) -> bool:
        """
        Пора ли запускать.

        Три условия. Нужный день недели; назначенное время уже наступило, но не
        слишком давно; и сегодня ещё не запускали.

        Последнее условие — главное: без него протокол срабатывал бы на каждом
        тике службы в течение всего льготного получаса.
        """
        if not self.enabled or not self.matches_day(now):
            return False

        назначено = now.replace(hour=self.hour, minute=self.minute,
                                second=0, microsecond=0)

        if now < назначено:
            return False

        if now - назначено > timedelta(minutes=GRACE_MINUTES):
            # Пропущенное не догоняем: утренний протокол вечером не нужен.
            return False

        if last_run is not None and last_run >= назначено:
            return False

        return True

    # ---- как это выглядит ----

    def human(self) -> str:
        """Расписание словами — для интерфейса и для ответа голосом."""
        время = f"{self.hour:02d}:{self.minute:02d}"

        if not self.days:
            return f"каждый день в {время}"
        if self.days == БУДНИ:
            return f"по будням в {время}"
        if self.days == ВЫХОДНЫЕ:
            return f"по выходным в {время}"

        дни = ", ".join(ИМЕНА_ДНЕЙ[д] for д in self.days)
        return f"{дни} в {время}"

    def to_dict(self) -> dict:
        return {"hour": self.hour, "minute": self.minute,
                "days": list(self.days), "enabled": self.enabled}


def parse(text: str) -> Optional[Schedule]:
    """
    Разобрать расписание из сказанного.

    Возвращает None, если времени в строке нет: без него расписание
    бессмысленно, а угадывать час — худшее, что можно сделать. Лучше честно
    отказаться, чем запустить протокол не тогда, когда ждут.
    """
    строка = (text or "").strip().lower()
    if not строка:
        return None

    # ---- время ----
    часы = минуты = None

    совпало = _ВРЕМЯ.search(строка)
    if совпало:
        часы, минуты = int(совпало.group(1)), int(совпало.group(2))
    else:
        # «в 9» — без минут. Только с предлогом: иначе «пн 9» и любое число в
        # строке сойдёт за время.
        час = _ЧАС.search(строка)
        if час:
            часы, минуты = int(час.group(1)), 0

    if часы is None or not (0 <= часы <= 23 and 0 <= минуты <= 59):
        return None

    # ---- дни ----
    дни: List[int] = []

    if "будн" in строка or "рабочие дни" in строка:
        дни = list(БУДНИ)
    elif "выходн" in строка:
        дни = list(ВЫХОДНЫЕ)
    elif "ежедневно" in строка or "каждый день" in строка:
        дни = []
    else:
        # Перечисление и промежутки: «пн, ср, пт», «пн-пт».
        промежуток = re.search(r"\b(пн|вт|ср|чт|пт|сб|вс)\s*[-–—]\s*(пн|вт|ср|чт|пт|сб|вс)\b",
                               строка)
        if промежуток:
            начало = ДНИ[промежуток.group(1)]
            конец = ДНИ[промежуток.group(2)]
            дни = (list(range(начало, конец + 1)) if начало <= конец
                   else list(range(начало, 7)) + list(range(0, конец + 1)))
        else:
            for слово, номер in ДНИ.items():
                if re.search(rf"(?<![а-яё]){слово}(?![а-яё])", строка):
                    дни.append(номер)

    return Schedule(hour=часы, minute=минуты, days=дни)
