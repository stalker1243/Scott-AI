"""
Подсказка распознаванию: что Scott ожидает услышать.

ЗАЧЕМ. Whisper принимает подсказку и склоняется к словам из неё. Разница на
живой проверке оказалась не косметической:

    сказано: «открой вижуал студио код»
    без подсказки:  «визуал студия у кода»
    с подсказкой:   «Visual Studio Code»

Именно на этом голос и проигрывал чату. В чате человек пишет «Google Chrome» —
Scott находит программу и открывает. Голосом получалось «открой кукол хром» (не
выдумка — так записано в журнале услышанного), и найти по такому названию было
нечего. Возможности при этом одинаковые: разбор у голоса и чата общий, вся
разница была в тексте, который до него доходил.

ПОЧЕМУ НЕ ВЕСЬ СПИСОК ПРОГРАММ. На этой машине их 207. Длинная подсказка сбивает
распознавание остального: модель начинает подгонять услышанное под неё, и
обычная фраза превращается в набор названий. Поэтому берётся пересечение двух
списков — того, что люди произносят по-английски, и того, что действительно
установлено.
"""

from __future__ import annotations

from typing import List, Optional

# Основа подсказки: как к Scott обращаются.
#
# Без неё «Скотт, какая погода» распознаётся как «Скот, какая погода», а
# непрочитанное имя означает, что человека не услышали вовсе.
BASE_PROMPT = "Скотт, открой браузер. Скотт, закрой программу. Скотт, напомни мне."

# Названия, которые произносят по-английски, а пишут латиницей.
#
# Список нужен не сам по себе: из него берутся только те программы, которые на
# этой машине действительно стоят. Русские названия сюда не нужны — с ними
# Whisper справляется и так.
KNOWN_APPS = [
    "Google Chrome", "Discord", "Telegram", "Visual Studio Code", "Steam",
    "Spotify", "Firefox", "Opera", "Photoshop", "Blender", "OBS Studio",
    "Notion", "Figma", "Zoom", "Skype", "Unity", "Docker Desktop",
    "Android Studio", "PyCharm", "IntelliJ IDEA", "Postman", "Git Bash",
]

# Сколько названий класть в подсказку.
#
# Десять — предел, за которым подсказка начинает мешать: модель тянет к ней
# обычные слова. Проверять стоит на фразе без единого названия программы —
# если она поехала, названий слишком много.
MAX_APPS = 10

_cached: Optional[str] = None


def installed_known_apps(limit: int = MAX_APPS) -> List[str]:
    """
    Известные программы, которые действительно установлены на этой машине.

    Каталог тот же, которым пользуется сам Scott, когда ищет программу по
    названию: список из головы подсказывал бы модели то, чего здесь нет.
    """
    try:
        try:
            from . import app_resolver
        except ImportError:
            import app_resolver

        каталог = set()
        for источник in (app_resolver._get_startapps_index,
                         app_resolver._get_shortcut_index):
            try:
                каталог.update(источник().keys())
            except Exception:
                continue
    except Exception:
        # Каталог не собрался — подсказка останется без названий. Это хуже, чем
        # с ними, но лучше, чем сорванное распознавание.
        return []

    найденные = []
    for название in KNOWN_APPS:
        ключ = название.lower()
        if any(ключ in запись for запись in каталог):
            найденные.append(название)

        if len(найденные) >= limit:
            break

    return найденные


def prompt() -> str:
    """
    Подсказка целиком. Собирается один раз: каталог программ стоит почти
    секунду, а меняется он не чаще, чем человек ставит новые программы.
    """
    global _cached

    if _cached is None:
        программы = installed_known_apps()

        _cached = (f"{BASE_PROMPT} Программы: {', '.join(программы)}."
                   if программы else BASE_PROMPT)

    return _cached


def reset() -> None:
    """Забыть собранную подсказку — например, после установки новых программ."""
    global _cached
    _cached = None
