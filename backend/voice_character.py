"""
Характер голоса: обработка синтезированной речи.

ЗАЧЕМ ЭТО ЗДЕСЬ. Голосов у локальной модели пять, и все они обычные
человеческие. Сделать звучание узнаваемым — «как у помощника», а не «как у
диктора» — сменой голоса нельзя: их просто нет других. Зато можно обработать
готовый звук, и разница слышна сразу.

ЧТО ЗДЕСЬ НЕ ДЕЛАЕТСЯ. Не воспроизводится звучание чужих вымышленных
помощников — ни голос, ни манера. Характеры собраны из обычных приёмов работы
со звуком и названы по тому, что делают.

ЦЕНА. Обработка секунды речи занимает единицы миллисекунд: это свёртки и
фильтры над массивом, который уже лежит в памяти. На фоне синтеза (сто с
лишним миллисекунд) не заметно.

ОСТОРОЖНО С КЭШЕМ. Готовые реплики лежат на диске, и характер входит в ключ:
иначе после смены характера вернулся бы старый файл, обработанный по-прежнему,
и человек решил бы, что настройка не работает.
"""

from __future__ import annotations

from typing import Dict

import numpy as np

try:
    from scipy import signal as _signal
    HAS_SCIPY = True
except ImportError:  # pragma: no cover — без scipy остаётся «Обычный»
    _signal = None
    HAS_SCIPY = False


# Характеры звучания — то, что человек видит списком.
CHARACTERS: Dict[str, str] = {
    "natural": "Обычный — как синтезировано",
    "clear": "Чёткий — ровный и разборчивый, по-дикторски",
    "speaker": "Из динамика — будто звучит в комнате",
    "synthetic": "Синтетический — с машинным призвуком",
}

DEFAULT_CHARACTER = "natural"


def _нормализовать(звук: np.ndarray, предел: float = 0.97) -> np.ndarray:
    """
    Привести громкость к пределу.

    Обязательный шаг после любой обработки: сумма задержек и подъём частот
    легко выводят сигнал за единицу, а всё, что выше, обрезается в треск.
    """
    пик = float(np.max(np.abs(звук))) if звук.size else 0.0

    if пик <= 1e-6:
        return звук

    return (звук / пик * предел).astype(np.float32)


def _сжать(звук: np.ndarray, порог: float = 0.25, отношение: float = 3.0) -> np.ndarray:
    """
    Выровнять громкость: тихое подтянуть, громкое придержать.

    Речь помощника слушают вполуха, занимаясь другим, и провалы в громкости
    означают непонятые слова. Сжатие мягкое — без него голос звучит
    «накачанным», и это утомляет за день сильнее, чем помогает.
    """
    огибающая = np.abs(звук)

    # Сглаживаем огибающую, иначе сжатие отработает по каждому отсчёту и даст
    # характерное искажение вместо ровной громкости.
    окно = max(1, int(0.005 * 48000))
    сглаженная = np.convolve(огибающая, np.ones(окно) / окно, mode="same")

    усиление = np.ones_like(звук)
    громко = сглаженная > порог
    усиление[громко] = (порог + (сглаженная[громко] - порог) / отношение) / сглаженная[громко]

    return (звук * усиление).astype(np.float32)


def _полоса(звук: np.ndarray, частота: int, низ: float, верх: float) -> np.ndarray:
    """Оставить полосу частот — так звучит небольшой динамик."""
    if not HAS_SCIPY:
        return звук

    низ = max(20.0, низ)
    верх = min(верх, частота / 2 - 100)

    секции = _signal.butter(4, [низ, верх], btype="band", fs=частота, output="sos")
    return _signal.sosfilt(секции, звук).astype(np.float32)


def _подъём_верхов(звук: np.ndarray, частота: int, от: float = 3000.0,
                   сила: float = 0.45) -> np.ndarray:
    """
    Прибавить верхних частот — в них живёт разборчивость согласных.

    Делается сложением с отфильтрованной копией, а не полочным фильтром:
    результат мягче, а кода меньше.
    """
    if not HAS_SCIPY:
        return звук

    секции = _signal.butter(2, min(от, частота / 2 - 100), btype="high",
                            fs=частота, output="sos")
    верх = _signal.sosfilt(секции, звук)

    return (звук + верх * сила).astype(np.float32)


def _отголосок(звук: np.ndarray, частота: int, задержка: float = 0.035,
               затухание: float = 0.28, повторов: int = 3) -> np.ndarray:
    """
    Короткое эхо — ощущение, что голос звучит в комнате, а не в голове.

    Хвост нарочно короткий: длинный превращает помощника в объявление на
    вокзале, и разобрать быстрый ответ становится трудно.
    """
    итог = звук.copy()
    шаг = max(1, int(задержка * частота))

    for n in range(1, повторов + 1):
        сдвиг = шаг * n
        if сдвиг >= len(звук):
            break

        итог[сдвиг:] += звук[:-сдвиг] * (затухание ** n)

    return итог.astype(np.float32)


def _призвук(звук: np.ndarray, частота: int) -> np.ndarray:
    """
    Машинный призвук: копия голоса, слегка расстроенная по высоте.

    Приём тот же, которым делают хор из одного голоса, только сдвиг маленький.
    Ухо не слышит второй голос отдельно — оно слышит, что звучание не вполне
    живое. Этого и добиваемся.
    """
    if len(звук) < 100:
        return звук

    # Растягиваем копию на четверть процента: выходит расстройка примерно в
    # четыре цента — ровно та грань, за которой начинается слышимая фальшь.
    длина = int(len(звук) * 1.0025)
    точки = np.linspace(0, len(звук) - 1, длина)
    копия = np.interp(точки, np.arange(len(звук)), звук)[:len(звук)]

    если_короче = len(копия)
    смесь = звук.copy()
    смесь[:если_короче] += копия * 0.35

    return смесь.astype(np.float32)


def apply(звук: np.ndarray, частота: int, character: str = DEFAULT_CHARACTER) -> np.ndarray:
    """
    Придать звучанию выбранный характер.

    Неизвестный характер — не повод остаться без голоса: возвращаем как есть.
    """
    if character == "natural" or character not in CHARACTERS:
        return звук

    звук = звук.astype(np.float32)

    if character == "clear":
        звук = _сжать(звук)
        звук = _подъём_верхов(звук, частота, от=2500.0, сила=0.35)

    elif character == "speaker":
        звук = _полоса(звук, частота, 280.0, 5200.0)
        звук = _сжать(звук, порог=0.2, отношение=4.0)
        звук = _отголосок(звук, частота, задержка=0.028, затухание=0.22)

    elif character == "synthetic":
        звук = _призвук(звук, частота)
        звук = _подъём_верхов(звук, частота, от=3500.0, сила=0.5)
        звук = _отголосок(звук, частота, задержка=0.018, затухание=0.18, повторов=2)
        звук = _сжать(звук, порог=0.22, отношение=3.5)

    return _нормализовать(звук)


def apply_to_file(path: str, character: str = DEFAULT_CHARACTER) -> bool:
    """
    Обработать готовый файл на месте.

    Возвращает True, если файл изменён. Любая беда здесь — не повод остаться
    без ответа: необработанный голос всё равно голос.
    """
    if character == "natural" or character not in CHARACTERS:
        return False

    try:
        import soundfile as sf

        звук, частота = sf.read(path, dtype="float32")

        # Многоканальный звук обрабатываем по одному каналу: у синтеза он
        # всё равно один, а гадать здесь незачем.
        if звук.ndim > 1:
            звук = звук[:, 0]

        sf.write(path, apply(звук, частота, character), частота)
        return True
    except Exception as e:
        print(f"⚠️ Характер голоса не применён: {e}")
        return False
