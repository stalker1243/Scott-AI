"""
Сколько Scott говорит вслух.

Замер, с которого всё началось: на вопрос «что такое фотосинтез» ответ ИИ
занимал 583 знака, и Scott читал его сорок три секунды. Всё это время микрофон
приглушён — иначе Scott слышит себя из колонок и принимает собственный ответ за
новую команду, — то есть перебить его нельзя даже словом.

Речь идёт вдвое медленнее чтения: в чате тот же ответ читают глазами за пару
секунд. Поэтому краткость нужна только вслух, и вводится она в двух местах.

Главное — попросить у модели сразу короткий ответ, когда вопрос задан голосом:
тогда он и короткий, и целый. Обрезка остаётся страховкой на случай, когда
модель просьбу не выполнила.
"""

import pytest

pytestmark = pytest.mark.unit


@pytest.fixture(scope="module")
def речь():
    try:
        import speech_text
    except ImportError:  # pragma: no cover — запуск из корня репозитория
        from backend import speech_text
    return speech_text


ДЛИННЫЙ_ОТВЕТ = (
    "Фотосинтез это процесс превращения света в энергию. "
    "Зелёные растения поглощают углекислый газ и воду, а под действием "
    "солнечного света превращают их в глюкозу и кислород. "
    "Происходит это в хлоропластах, где находится хлорофилл. "
    "Благодаря этому процессу в атмосфере поддерживается кислород."
)


# ==================== Обрезка вслух ====================

@pytest.mark.parametrize("текст", [
    "Готово.",
    "Открыл браузер.",
    "Сейчас двадцать три часа сорок минут.",
])
def test_short_answers_untouched(речь, текст):
    """
    Короткий ответ не трогаем.

    «Готово» обрезать нечего, и приписка про чат к нему не нужна — она
    выглядела бы обещанием подробностей, которых нет.
    """
    assert речь.shorten_for_speech(текст) == текст


def test_long_answer_is_cut_to_sentences(речь):
    """Длинный ответ обрезается по границе предложения, а не по числу знаков."""
    произносимое = речь.shorten_for_speech(ДЛИННЫЙ_ОТВЕТ)

    assert len(произносимое) < len(ДЛИННЫЙ_ОТВЕТ)
    assert произносимое.startswith("Фотосинтез это процесс")
    # Фраза, оборванная на середине слова, звучит как поломка.
    assert произносимое.rstrip().endswith(".")


def test_cut_answer_says_where_the_rest_is(речь):
    """
    Обрезанный ответ сообщает, что есть продолжение.

    Без этого человек решит, что Scott оборвался на полуслове или не знает
    остального.
    """
    произносимое = речь.shorten_for_speech(ДЛИННЫЙ_ОТВЕТ)
    assert речь.SPOKEN_TAIL in произносимое


def test_single_long_sentence_survives(речь):
    """
    Одно длинное предложение произносится целиком.

    Резать его негде: обрывок на середине мысли хуже, чем долгая, но связная
    фраза. Лучше долго, чем бессмысленно.
    """
    одно = "Фотосинтез это " + "очень " * 40 + "длинный процесс."
    assert речь.shorten_for_speech(одно) == одно


def test_empty_text(речь):
    assert речь.shorten_for_speech("") == ""
    assert речь.shorten_for_speech("   ") == ""


def test_abbreviations_do_not_split_sentences(речь):
    """
    Точка в сокращении или числе — не конец предложения.

    Иначе «версия 1.2» разрывает фразу посередине, и вслух звучит обрубок.
    """
    текст = "Установлена версия 1.2. Всё работает."
    куски = речь._split_sentences(текст)
    assert len(куски) == 2, куски


# ==================== Короткий ответ от модели ====================

def test_voice_prompt_forbids_markup():
    """
    Голосовой запрос к модели прямо запрещает разметку.

    Списки и заголовки Scott зачитывает вслух как есть: «решётка решётка
    почему небо голубое» — именно это и прозвучало на живой проверке, пока
    признак «спросили голосом» не доходил до самого запроса.
    """
    try:
        import intelligent_answerer as ia
    except ImportError:  # pragma: no cover
        from backend import intelligent_answerer as ia

    запрос = ia.BRIEF_SYSTEM_PROMPT.lower()
    assert "списк" in запрос
    assert "коротк" in запрос
    assert ia.BRIEF_MAX_TOKENS < 400, "предел не ограничивает длину"


def test_brief_reaches_the_model(monkeypatch):
    """
    Признак «спросили голосом» доходит до запроса к модели.

    Первая попытка прошла мимо: короткий запрос добавили в одном месте, а
    ответы на вопросы идут другим путём — через локального отвечающего, который
    сам обращается к модели. Проверка показала ответ на 546 знаков со списками,
    то есть длиннее обычного.
    """
    try:
        import question_answerer as qa_module
    except ImportError:  # pragma: no cover
        from backend import question_answerer as qa_module

    полученные = {}

    class ЗаглушкаМодели:
        enabled = True

        def answer_question(self, question, brief=False):
            полученные["brief"] = brief
            return "Первое предложение. Второе предложение. Третье предложение."

    import sys
    monkeypatch.setitem(sys.modules, "intelligent_answerer", ЗаглушкаМодели())
    sys.modules["intelligent_answerer"].intelligent_answerer = ЗаглушкаМодели()

    отвечающий = qa_module.QuestionAnswerer()
    ответ = отвечающий._ai_fallback("что такое фотосинтез", "normal", brief=True)

    assert полученные.get("brief") is True, "признак не дошёл до модели"
    # Голосом — одно предложение, что бы ни стояло в подробности.
    assert ответ == "Первое предложение."
