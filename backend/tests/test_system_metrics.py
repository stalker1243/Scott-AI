"""
Метрики машины: нагрузка и заполненность — разные величины.

Замечание с живого просмотра: лаунчер показывал диск на восемьдесят процентов,
хотя в диспетчере он почти не работал. Ошибки в расчёте не было — считалось
совершенно другое: доля занятого МЕСТА вместо доли ВРЕМЕНИ, когда диск был
занят работой. Числа не имеют друг к другу отношения, и на забитом диске, к
которому никто не обращается, первое равно ста, а второе нулю.

Первая починка тоже оказалась неверной, и это стоит помнить. Она считала
нагрузку по полям `read_time` и `write_time` у счётчиков ввода-вывода — тем,
что psutil обещает. На Linux они заполнены, а на Windows нет: за время записи
ста мегабайт `write_bytes` вырос на все сто, а `write_time` остался нулём. То
есть на основной для проекта системе честный по виду расчёт молча давал ноль
при любой нагрузке, и заметить это можно было только живой проверкой.

Поэтому на Windows берётся тот же счётчик производительности, по которому
рисует диспетчер задач.
"""

import pytest

pytestmark = pytest.mark.unit


try:
    import disk_load
    import system_monitor
except ImportError:  # pragma: no cover — запуск из корня репозитория
    from backend import disk_load
    from backend import system_monitor


class Счётчики:
    """Подделка счётчиков ввода-вывода: время обслуживания запросов."""

    def __init__(self, read_time, write_time):
        self.read_time = read_time
        self.write_time = write_time


@pytest.fixture
def измеритель(monkeypatch):
    """
    Измеритель, считающий по времени обслуживания.

    Путь через счётчик Windows проверить подделкой нельзя — он живёт в
    системе, а не в нашем коде; для него есть отдельная живая проверка ниже.
    """
    monkeypatch.setattr(disk_load, "WINDOWS", False)
    return disk_load.DiskLoad()


# ==================== Нагрузка по времени обслуживания ====================

def test_first_reading_is_zero(измеритель, monkeypatch):
    """
    Первый замер показывает ноль.

    Счётчики отдают время, накопленное с запуска системы, и сравнивать его не
    с чем. Показать накопленное за сутки как нагрузку прямо сейчас значило бы
    соврать в первую же секунду после старта.
    """
    monkeypatch.setattr(disk_load.psutil, "disk_io_counters",
                        lambda: Счётчики(500_000, 300_000))

    assert измеритель.read() == 0.0


def test_idle_disk_reads_zero(измеритель, monkeypatch):
    """Диск, который ничего не делал между замерами, показывает ноль."""
    monkeypatch.setattr(disk_load.psutil, "disk_io_counters",
                        lambda: Счётчики(1000, 500))

    измеритель.read()
    assert измеритель.read() == 0.0


def test_busy_disk_reads_high(измеритель, monkeypatch):
    """
    Диск, занятый почти всё время, показывает почти сто процентов.

    Полсекунды работы за полсекунды времени — это сто процентов занятости, и
    ровно так же считает диспетчер задач.
    """
    часы = [0.0]
    monkeypatch.setattr(disk_load.time, "monotonic", lambda: часы[0])

    время = [0]
    monkeypatch.setattr(disk_load.psutil, "disk_io_counters",
                        lambda: Счётчики(время[0], 0))

    измеритель.read()

    часы[0] = 0.5
    время[0] = 500        # 500 мс работы за 0.5 с

    assert измеритель.read() == pytest.approx(100.0, abs=1.0)


def test_load_never_exceeds_hundred(измеритель, monkeypatch):
    """
    Параллельные запросы к нескольким дискам дают в сумме больше ста.

    Человеку такое число ничего не скажет, а рядом с процентами процессора
    выглядит поломкой.
    """
    часы = [0.0]
    monkeypatch.setattr(disk_load.time, "monotonic", lambda: часы[0])

    время = [0]
    monkeypatch.setattr(disk_load.psutil, "disk_io_counters",
                        lambda: Счётчики(время[0], 0))

    измеритель.read()

    часы[0] = 1.0
    время[0] = 4000       # четыре диска отработали по секунде

    assert измеритель.read() == 100.0


def test_broken_counters_do_not_raise(измеритель, monkeypatch):
    """
    Счётчиков может не быть вовсе.

    На части систем psutil их не отдаёт. Уронить из-за этого весь опрос метрик
    было бы несоразмерно: остальные три величины считаются прекрасно.
    """
    monkeypatch.setattr(disk_load.psutil, "disk_io_counters", lambda: None)
    assert измеритель.read() == 0.0

    def взрыв():
        raise OSError("нет доступа к счётчикам")

    monkeypatch.setattr(disk_load.psutil, "disk_io_counters", взрыв)
    assert измеритель.read() == 0.0


# ==================== Живая проверка ====================

def test_load_is_a_percentage_on_this_machine():
    """
    На этой машине нагрузка считается и выглядит как проценты.

    Проверка живая и намеренно слабая: требовать конкретного числа от чужой
    машины нельзя. Но молчаливый ноль при любой нагрузке — ровно то, чем
    кончилась первая починка, — она поймает вместе с остальными способами
    сломать расчёт.
    """
    измеритель = disk_load.DiskLoad()

    for _ in range(3):
        значение = измеритель.read()
        assert isinstance(значение, float)
        assert 0.0 <= значение <= 100.0

    assert измеритель.source


# ==================== Метрики целиком ====================

def test_metrics_report_load_and_usage_separately():
    """
    В метриках есть и нагрузка, и заполненность, и это разные поля.

    Заполненность никуда не делась — она полезна сама по себе и показана в
    подписи. Важно, чтобы её больше не выдавали за нагрузку.
    """
    монитор = system_monitor.SystemMonitor()
    метрики = монитор.get_metrics()

    assert "disk" in метрики
    assert "disk_usage" in метрики

    assert 0 <= метрики["disk"] <= 100
    assert 0 <= метрики["disk_usage"] <= 100
