"""
Журнал услышанного: что Scott расслышал и что из этого вышло.

ЗАЧЕМ ОН НУЖЕН. Голосом Scott умеет меньше, чем в чате, — и это первое, что
замечает человек, попробовав обе двери. Но разбор у голоса и чата ОДИН И ТОТ
ЖЕ: `_process_command_impl` не знает, откуда пришла фраза. Значит дело не в
возможностях, а в тексте, который до разбора доходит.

Проверить это было нечем. За один вечер до распознавания дошли 29 фраз, а до
разбора команды — 10; куда делись остальные девятнадцать, узнать было
неоткуда: распознанное печаталось в вывод и нигде не оставалось.
"""

import json

import pytest

pytestmark = pytest.mark.unit

try:
    import heard_log
except ImportError:  # pragma: no cover — запуск из корня репозитория
    from backend import heard_log


@pytest.fixture
def журнал(tmp_path, monkeypatch):
    """Журнал в своей папке — настоящую речь человека не трогаем."""
    monkeypatch.setattr(heard_log, "LOG_PATH", tmp_path / "heard.jsonl")
    return heard_log


def test_услышанное_сохраняется(журнал):
    журнал.record("Скотт, открой браузер", "выполнена", "открой браузер")

    записи = журнал.read()

    assert len(записи) == 1
    assert записи[0]["text"] == "Скотт, открой браузер"
    assert записи[0]["command"] == "открой браузер"
    assert записи[0]["outcome"] == "выполнена"


def test_прошедшее_мимо_тоже_записывается(журнал):
    """
    Самое важное здесь. Фраза, в которой Scott не узнал своё имя, — это и есть
    потерянная команда, и именно её надо увидеть: по ней ясно, какой вариант
    имени не читается.
    """
    журнал.record("Скотти открой браузер", "мимо")

    записи = журнал.read()

    assert записи[0]["outcome"] == "мимо"
    assert записи[0]["command"] == ""


def test_сводка_показывает_доли(журнал):
    """
    Если Scott слышит сказанное, но узнаёт имя в трети случаев, лечить надо
    имя, а не разбор команд. Сводка отвечает на этот вопрос одним взглядом.
    """
    журнал.record("Скотт, открой браузер", "выполнена", "открой браузер")
    журнал.record("а потом я пошёл домой", "мимо")
    журнал.record("Скотти, закрой дискорд", "мимо")

    сводка = журнал.summary()

    assert сводка["total"] == 3
    assert сводка["outcomes"]["мимо"] == 2
    assert сводка["outcomes"]["выполнена"] == 1


def test_журнал_не_растёт_бесконечно(журнал):
    for n in range(журнал.MAX_ENTRIES + 40):
        журнал.record(f"фраза {n}", "мимо")

    assert len(журнал.read()) == журнал.MAX_ENTRIES


def test_услышанное_можно_забыть(журнал):
    """Это речь человека, и он вправе её стереть."""
    журнал.record("Скотт, открой браузер", "выполнена")

    журнал.clear()

    assert журнал.read() == []


def test_испорченная_строка_не_губит_остальные(журнал):
    журнал.record("Скотт, открой браузер", "выполнена")
    журнал.LOG_PATH.write_text(
        json.dumps({"at": 1, "text": "первая", "outcome": "мимо"}, ensure_ascii=False)
        + "\nне json\n"
        + json.dumps({"at": 2, "text": "вторая", "outcome": "мимо"}, ensure_ascii=False),
        encoding="utf-8")

    записи = журнал.read()

    assert [з["text"] for з in записи] == ["первая", "вторая"]


def test_звук_не_сохраняется(журнал):
    """
    Хранить записи голоса без ведома человека помощник не должен. В журнале
    только текст — и длина записи, чтобы видеть, сколько он говорил.
    """
    журнал.record("Скотт, открой браузер", "выполнена", "открой браузер", seconds=1.6)

    запись = журнал.read()[0]

    assert set(запись) == {"at", "text", "outcome", "command", "seconds"}
    assert запись["seconds"] == 1.6
