"""
Расписание протоколов: когда Scott запускает их сам.

ЗАЧЕМ ЭТО ЕСТЬ. Протокол — одна фраза вместо четырёх, но фразу всё равно надо
сказать. С расписанием он становится настоящей автоматизацией: «по будням в
девять» человек приходит к готовому рабочему столу, ничего не говоря.

ЧТО ЗДЕСЬ ВАЖНЕЕ ВСЕГО. Не разбор строки — он простой, — а два правила
срабатывания, на которых такие вещи обычно и ломаются: протокол не должен
запускаться дважды за одно утро и не должен догонять пропущенное. Утренний
протокол, сработавший вечером, — не «лучше поздно», а помеха: человек давно
начал день сам.
"""

from datetime import datetime, timedelta

import pytest

pytestmark = pytest.mark.unit

try:
    import protocol_schedule
    from protocols import Protocol
except ImportError:  # pragma: no cover — запуск из корня репозитория
    from backend import protocol_schedule
    from backend.protocols import Protocol


ПОНЕДЕЛЬНИК = datetime(2026, 9, 21, 9, 0)
СУББОТА = datetime(2026, 9, 19, 9, 0)


# ==================== Как это записывают ====================

@pytest.mark.parametrize("строка,ожидание", [
    ("каждый день в 9:00", "каждый день в 09:00"),
    ("по будням в 09:30", "по будням в 09:30"),
    ("пн-пт в 9:00", "по будням в 09:00"),
    ("по выходным в 11:00", "по выходным в 11:00"),
    ("пн, ср, пт в 18:00", "пн, ср, пт в 18:00"),
    ("в 23:00", "каждый день в 23:00"),
])
def test_расписание_понимается_как_сказано(строка, ожидание):
    """
    Человек пишет то же, что сказал бы вслух, — тот же подход, что и у шагов
    протокола: ему не нужно знать ни одного названия.
    """
    расписание = protocol_schedule.parse(строка)

    assert расписание is not None, f"«{строка}» не разобрано"
    assert расписание.human() == ожидание


@pytest.mark.parametrize("строка", ["каждый день", "по будням", "когда-нибудь", ""])
def test_без_времени_расписание_не_принимается(строка):
    """
    Угадать час — худшее, что можно сделать: протокол сработает не тогда, когда
    ждут, и человек не поймёт почему. Честный отказ лучше.
    """
    assert protocol_schedule.parse(строка) is None


# ==================== Когда срабатывает ====================

def протокол(строка_расписания: str) -> Protocol:
    return Protocol.from_dict({
        "name": "Работа",
        "steps": ["открой браузер"],
        "schedule": строка_расписания,
    })


def test_срабатывает_в_свой_день_и_час():
    assert протокол("по будням в 09:00").due(ПОНЕДЕЛЬНИК.replace(minute=5))


def test_не_срабатывает_в_чужой_день():
    assert not протокол("по будням в 09:00").due(СУББОТА.replace(minute=5))


def test_не_срабатывает_раньше_времени():
    assert not протокол("по будням в 09:00").due(ПОНЕДЕЛЬНИК.replace(hour=8, minute=59))


def test_пропущенное_не_догоняется():
    """
    Главное правило. Компьютер был выключен в девять — протокол «Работа» не
    должен запускаться в семь вечера: человек ждал его утром, а вечером он уже
    помеха.
    """
    вечером = ПОНЕДЕЛЬНИК.replace(hour=19)

    assert not протокол("по будням в 09:00").due(вечером)


def test_небольшое_опоздание_прощается():
    """
    Scott мог быть занят, спать вместе с компьютером или ещё запускаться.
    Полчаса — столько, в течение которых утренний протокол ещё уместен.
    """
    чуть_позже = ПОНЕДЕЛЬНИК + timedelta(minutes=20)

    assert протокол("по будням в 09:00").due(чуть_позже)


def test_дважды_за_утро_не_срабатывает():
    """
    Второе главное правило. Служба тикает раз в пятнадцать секунд, и без
    проверки «сегодня уже запускали» протокол выполнялся бы сто раз подряд весь
    льготный получас.
    """
    п = протокол("по будням в 09:00")
    п.last_run = ПОНЕДЕЛЬНИК.replace(minute=1).isoformat()

    assert not п.due(ПОНЕДЕЛЬНИК.replace(minute=10))


def test_вчерашний_запуск_не_мешает_сегодняшнему():
    """Пара к проверке выше: отметка о вчерашнем запуске не должна отменять сегодняшний."""
    п = протокол("по будням в 09:00")
    п.last_run = (ПОНЕДЕЛЬНИК - timedelta(days=1)).isoformat()

    assert п.due(ПОНЕДЕЛЬНИК.replace(minute=5))


def test_выключенный_протокол_не_срабатывает():
    п = протокол("по будням в 09:00")
    п.enabled = False

    assert not п.due(ПОНЕДЕЛЬНИК.replace(minute=5))


def test_без_расписания_не_срабатывает_никогда():
    """Протокол без расписания ждёт, пока его позовут, — и это обычный случай."""
    п = Protocol.from_dict({"name": "Работа", "steps": ["открой браузер"]})

    assert not п.due(ПОНЕДЕЛЬНИК.replace(minute=5))


# ==================== Хранение ====================

def test_расписание_переживает_сохранение():
    """
    Протокол лежит в файле, и расписание должно возвращаться оттуда тем же:
    иначе после перезапуска Scott перестанет будить человека по утрам, ничего
    об этом не сказав.
    """
    исходный = протокол("пн, ср, пт в 18:00")

    восстановленный = Protocol.from_dict(исходный.to_dict())

    assert восстановленный.schedule.human() == "пн, ср, пт в 18:00"


def test_расписание_видно_словами():
    """Интерфейсу и ответу голосом нужны слова, а не часы с номерами дней."""
    данные = протокол("по будням в 09:00").to_dict()

    assert данные["schedule_text"] == "по будням в 09:00"


# ==================== Неудавшийся запуск ====================

def test_неудачная_попытка_отмечается_но_не_считается_запуском(tmp_path):
    """
    Протокол, упавший на первом шаге, нельзя оставлять без отметки: служба
    тикает раз в пятнадцать секунд, и он пробовался бы заново весь льготный
    получас — сотню раз подряд. Но и в счётчик запусков ему нельзя: он не
    выполнился, а цифра рядом с именем должна говорить правду.
    """
    from protocols import ProtocolStore

    хранилище = ProtocolStore(path=str(tmp_path / "protocols.json"))
    хранилище.add("Работа", ["открой браузер"], schedule="по будням в 09:00")
    п = хранилище.all()[0]

    хранилище.mark_attempt(п)

    assert п.runs == 0, "неудавшийся запуск попал в счётчик"
    assert п.last_run, "без отметки времени протокол пойдёт по кругу на каждом тике"
