"""
Память Scott: что он знает о своём человеке.

Это не кэш ответов из knowledge_base («на эту фразу уже отвечали»), а сведения,
которые человек велел запомнить: «я работаю в вечернюю смену», «мой проект на
C#». Помощник, которому каждый раз рассказывают одно и то же, помощником не
становится.

Две опасности, ради которых и написаны проверки.

Первая: записи уходят в КАЖДЫЙ запрос к модели. Память, растущая без предела,
однажды займёт собой весь запрос и вытеснит сам вопрос.

Вторая, тише: просьба «запомни, что…» по всем обычным признакам выглядит
вопросом — есть подлежащее, сказуемое и ни одного знакомого приказа. Уйдя к
модели, она кончилась бы вежливым «хорошо, запомнил», и никто ничего бы не
запомнил.
"""

import pytest

pytestmark = pytest.mark.unit

try:
    import memories
    import understanding
except ImportError:  # pragma: no cover — запуск из корня репозитория
    from backend import memories, understanding


@pytest.fixture
def память(tmp_path, monkeypatch):
    """Память со своим файлом — чтобы не трогать настоящую."""
    monkeypatch.setattr(memories, "STORE_PATH", tmp_path / "memories.json")
    return memories


# ==================== Хранение ====================

def test_запомненное_читается_обратно(память):
    память.add("Я работаю в вечернюю смену")

    записи = память.all_memories()

    assert len(записи) == 1
    assert записи[0]["text"] == "Я работаю в вечернюю смену"


def test_новое_сверху(память):
    """Список читают сверху, и свежее там нужнее старого."""
    память.add("Первое")
    память.add("Второе")

    assert память.all_memories()[0]["text"] == "Второе"


def test_повтор_не_заводит_вторую_запись(память):
    """
    Человек может сказать «запомни, что я пишу на C#» дважды — и два одинаковых
    пункта в списке выглядят как ошибка программы.
    """
    память.add("Я пишу на C#")
    итог = память.add("я пишу на c#")

    assert итог["success"]
    assert len(память.all_memories()) == 1
    assert "уже помнит" in итог.get("note", "")


def test_пустое_не_запоминается(память):
    итог = память.add("   ")

    assert not итог["success"]
    assert память.all_memories() == []


def test_забытое_исчезает(память):
    запись = память.add("Временное")["memory"]

    assert память.remove(запись["id"])["success"]
    assert память.all_memories() == []


def test_забыть_несуществующее_не_ошибка_программы(память):
    итог = память.remove("такого-нет")

    assert not итог["success"]
    assert итог["error"]


def test_очистка_по_категории_не_трогает_остальное(память):
    память.add("Факт", kind="fact")
    память.add("Задача", kind="task")

    память.clear(kind="task")

    осталось = память.all_memories()
    assert len(осталось) == 1
    assert осталось[0]["kind"] == "fact"


def test_испорченный_файл_не_роняет_запуск(память):
    """
    Память читается при каждом ответе. Падение здесь означало бы, что Scott
    перестал отвечать вовсе — из-за строки в файле.
    """
    память.STORE_PATH.parent.mkdir(parents=True, exist_ok=True)
    память.STORE_PATH.write_text("{это не список", encoding="utf-8")

    assert память.all_memories() == []


# ==================== Пределы ====================

def test_длинная_запись_обрезается(память):
    """Память — это короткие сведения, а не дневник."""
    итог = память.add("а" * 5000)

    assert len(итог["memory"]["text"]) == память.MAX_TEXT


def test_память_не_растёт_бесконечно(память):
    for n in range(память.MAX_TOTAL + 20):
        память.add(f"Запись номер {n}")

    assert len(память.all_memories()) == память.MAX_TOTAL


def test_вытесняются_самые_старые(память):
    """
    Забытое полгода назад обычно устарело, а редко нужное может понадобиться
    завтра. Поэтому вытесняем по возрасту, а не по частоте.
    """
    for n in range(память.MAX_TOTAL + 5):
        память.add(f"Запись номер {n}")

    тексты = [з["text"] for з in память.all_memories()]

    assert "Запись номер 0" not in тексты
    assert f"Запись номер {память.MAX_TOTAL + 4}" in тексты


def test_в_запрос_уходит_ограниченный_кусок(память):
    """
    Записи подмешиваются в КАЖДЫЙ запрос. Без предела память однажды вытеснила
    бы из него сам вопрос.
    """
    for n in range(память.MAX_TOTAL):
        память.add(f"Довольно длинная запись под номером {n}, чтобы набрать объём")

    добавка = память.prompt_addition()

    assert len(добавка) < память.MAX_PROMPT_CHARS + 200


# ==================== Дорога до модели ====================

def test_пустая_память_ничего_не_меняет(память):
    """Человек, ничего не просивший запомнить, получает прежнее поведение."""
    assert память.prompt_addition() == ""


def test_запомненное_доходит_до_модели(память):
    память.add("Я работаю в вечернюю смену")

    добавка = память.prompt_addition()

    assert "вечернюю смену" in добавка


# ==================== Просьба запомнить ====================

@pytest.mark.parametrize("фраза,ожидается", [
    ("запомни, что я работаю в вечернюю смену", "я работаю в вечернюю смену"),
    ("Запомни: мой проект на C#", "мой проект на C#"),
    ("имей в виду, что я сова", "я сова"),
    ("запиши что завтра встреча", "завтра встреча"),
])
def test_просьба_запомнить_узнаётся(фраза, ожидается):
    assert understanding.extract_memory(фраза) == ожидается


@pytest.mark.parametrize("фраза", [
    "напомни мне позвонить маме",     # это про напоминания, а не про память
    "что ты помнишь обо мне",         # вопрос, а не просьба
    "не запоминай это",
    "забудь всё",
    "открой блокнот",
])
def test_не_всякая_фраза_про_память_есть_просьба(фраза):
    """
    «Напомни» — совсем другая часть Scott, напоминания. Спутав их, мы завели бы
    в памяти записи вместо будильников.
    """
    assert understanding.extract_memory(фраза) is None


def test_само_слово_запомни_в_память_не_попадает():
    """
    В память должно попасть «я работаю в вечернюю смену», а не «запомни, что я
    работаю в вечернюю смену»: последнее Scott потом пересказал бы модели как
    есть.
    """
    итог = understanding.extract_memory("запомни, что я работаю в вечернюю смену")

    assert итог is not None
    assert "запомни" not in итог.lower()
