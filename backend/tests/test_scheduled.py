"""
Отложенные команды: сделать не сейчас, а когда придёт время.

«Напомни через час позвонить маме» Scott умел и раньше — и в назначенный час
произносил эти слова вслух. Отличие здесь одно: «через час запусти рендер» он
должен не напомнить, а выполнить.

Главная опасность тут — спутать одно с другим. «Напомни выключить компьютер» и
«выключи компьютер через час» отличаются одним глаголом, а последствия разные:
в первом случае Scott промолчит вместо дела, во втором — выключит компьютер,
когда его просили только напомнить.

Вторая опасность тише. Отложенное исполняется без человека: подтвердить или
остановить в назначенный час некому. Значит откладывать можно не всё.
"""

import pytest

pytestmark = pytest.mark.unit

try:
    import reminders
    import scheduled
except ImportError:  # pragma: no cover — запуск из корня репозитория
    from backend import reminders, scheduled


# ==================== Напомнить или сделать ====================

@pytest.mark.parametrize("фраза", [
    "напомни через час позвонить маме",
    "напомни в 18:00 про встречу",
    "напомни выключить компьютер вечером",
    "не забудь про совещание в 15:00",
])
def test_просьба_напомнить_остаётся_напоминанием(фраза):
    """
    Слово «напомни» решает всё: человек просит слов, а не дела. Выполнив это,
    Scott выключил бы компьютер, когда его просили только напомнить.
    """
    assert scheduled.is_reminder(фраза)


@pytest.mark.parametrize("фраза", [
    "через час запусти рендер",
    "выключи компьютер через два часа",
    "в 7 утра открой почту",
    "завтра утром запусти сборку",
])
def test_просьба_сделать_становится_командой(фраза):
    """
    Здесь глагола «напомни» нет — значит человек просит дела. Проговорив это
    вслух, Scott промолчал бы вместо работы.
    """
    assert not scheduled.is_reminder(фраза)


# ==================== Что достаётся исполнителю ====================

@pytest.mark.parametrize("фраза,ожидается", [
    ("через час запусти рендер", "запусти рендер"),
    ("выключи компьютер через два часа", "выключи компьютер"),
    ("Скотт, в 7 утра открой почту", "открой почту"),
])
def test_время_вырезается_а_команда_остаётся(фраза, ожидается):
    """
    В назначенный час исполняется то, что здесь останется. Срежь лишнее — и
    команда потеряет смысл; оставь время — и Scott попытается выполнить «через
    час запусти рендер» как приказ со словом «час» внутри.
    """
    assert reminders.strip_time(фраза) == ожидается


def test_глагол_действия_не_срезается():
    """
    Отличие от разбора напоминаний. Там срезается «напомни» — служебное слово.
    Здесь глагол и есть команда: без «запусти» от фразы не останется ничего.
    """
    итог = reminders.strip_time("через полчаса запусти сборку")

    assert "запусти" in итог


# ==================== Чего откладывать нельзя ====================

@pytest.mark.parametrize("опасное", sorted(scheduled.FORBIDDEN))
def test_опасное_не_откладывается(опасное):
    """
    В назначенный час рядом может никого не быть: спросить «точно удалить?»
    будет некому. Для таких действий отложенное исполнение — способ узнать о
    беде постфактум.
    """
    assert not scheduled.can_defer(опасное)


@pytest.mark.parametrize("обычное", ["open_app", "shutdown", "volume_up", "open_website"])
def test_обычное_откладывать_можно(обычное):
    assert scheduled.can_defer(обычное)


def test_отказ_объясняет_причину():
    """
    «Нельзя» без объяснения выглядит капризом программы. Человек должен понять,
    что дело не в запрете, а в том, что подтвердить будет некому.
    """
    текст = scheduled.refusal("delete_file")

    assert "некому" in текст or "не буд" in текст
    assert len(текст) > 40


# ==================== Служба умеет хранить вид ====================

def test_служба_помнит_что_это_команда(tmp_path, monkeypatch):
    """
    Вид записи переживает перезапуск: Scott работает в фоне, и отложенное на
    завтра должно сохраниться в файле вместе с тем, что это команда, а не
    напоминание.
    """
    monkeypatch.setattr(reminders, "STORE_PATH", tmp_path / "reminders.json")

    from datetime import datetime, timedelta

    служба = reminders.ReminderService()
    служба.add("запусти рендер", datetime.now() + timedelta(hours=1), kind="command")

    другая = reminders.ReminderService()
    сохранённое = другая.pending()

    assert len(сохранённое) == 1
    assert сохранённое[0].kind == "command"
    assert сохранённое[0].text == "запусти рендер"
