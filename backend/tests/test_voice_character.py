"""
Характер голоса: обработка синтезированной речи.

ЗАЧЕМ ЭТО ЕСТЬ. Голосов у локальной модели пять, и все они обычные
человеческие. Сделать звучание узнаваемым — «как у помощника», а не «как у
диктора» — сменой голоса нельзя: других просто нет. Зато можно обработать
готовый звук.

Проверяется не «красиво ли» — этого кодом не узнать, — а то, что обработка не
портит запись: не обрезает её в треск, не глушит до неразборчивости, не
растягивает и не теряет. И что при любой беде остаётся необработанный голос:
он всё равно голос.
"""

import numpy as np
import pytest

pytestmark = pytest.mark.unit

try:
    import voice_character
except ImportError:  # pragma: no cover — запуск из корня репозитория
    from backend import voice_character


ЧАСТОТА = 48000


@pytest.fixture
def речь():
    """Похожее на речь: несколько тонов голосового диапазона с огибающей."""
    время = np.linspace(0, 1.0, ЧАСТОТА, dtype=np.float32)
    волна = sum(np.sin(2 * np.pi * ч * время) / n
                for n, ч in enumerate((180, 360, 720, 1400), start=1))
    огибающая = np.abs(np.sin(2 * np.pi * 3 * время)) + 0.1

    return (волна * огибающая * 0.4).astype(np.float32)


@pytest.mark.parametrize("характер", list(voice_character.CHARACTERS))
def test_обработка_не_даёт_перегрузки(речь, характер):
    """
    Сумма задержек и подъём частот легко выводят сигнал за единицу, а всё, что
    выше, обрезается в треск. Это первое, что слышно, и слышно сразу.
    """
    итог = voice_character.apply(речь, ЧАСТОТА, характер)

    assert float(np.max(np.abs(итог))) <= 1.0


@pytest.mark.parametrize("характер", list(voice_character.CHARACTERS))
def test_длина_записи_сохраняется(речь, характер):
    """
    Речь по частям складывается в очередь проигрывателя: обработка, меняющая
    длину, рассыпала бы ответ на куски с паузами.
    """
    итог = voice_character.apply(речь, ЧАСТОТА, характер)

    assert len(итог) == len(речь)


@pytest.mark.parametrize("характер", list(voice_character.CHARACTERS))
def test_голос_не_глохнет(речь, характер):
    """
    Обработка не должна съедать громкость: ответ, который приходится
    переспрашивать, хуже необработанного.
    """
    было = float(np.sqrt(np.mean(речь ** 2)))
    стало = float(np.sqrt(np.mean(voice_character.apply(речь, ЧАСТОТА, характер) ** 2)))

    assert стало > было * 0.5


def test_обычный_характер_ничего_не_меняет(речь):
    """Выбор «как синтезировано» должен означать именно это."""
    итог = voice_character.apply(речь, ЧАСТОТА, "natural")

    assert np.array_equal(итог, речь)


def test_неизвестный_характер_не_лишает_голоса(речь):
    """
    Настройка могла прийти из файла, написанного другой версией. Остаться без
    ответа из-за незнакомого слова нельзя.
    """
    итог = voice_character.apply(речь, ЧАСТОТА, "какой-то-новый")

    assert np.array_equal(итог, речь)


def test_характеры_звучат_по_разному(речь):
    """
    Иначе настройка была бы обманом: человек выбирает, а слышит то же самое.
    """
    записи = {имя: voice_character.apply(речь, ЧАСТОТА, имя)
              for имя in voice_character.CHARACTERS}

    for имя, запись in записи.items():
        if имя == "natural":
            continue

        разница = float(np.mean(np.abs(запись - записи["natural"])))
        assert разница > 0.01, f"«{имя}» звучит как обычный"


def test_тишина_остаётся_тишиной():
    """
    На пустой записи нормализация делила бы на ноль. Тишина сюда попадает
    буднично: тихий режим, оборванная фраза, сбой синтеза.
    """
    тишина = np.zeros(ЧАСТОТА, dtype=np.float32)

    итог = voice_character.apply(тишина, ЧАСТОТА, "synthetic")

    assert not np.any(np.isnan(итог))
    assert float(np.max(np.abs(итог))) == 0.0
