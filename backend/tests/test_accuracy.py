"""
Точность разбора: одно число вместо ощущения.

ЗАЧЕМ ЭТО ЕСТЬ. Все дыры, найденные за сентябрь, нашлись СЛУЧАЙНО — споткнувшись
о них в работе. «Выключи компьютер» не работало никогда: Scott искал программу с
таким названием. «Убавь яркость» доходило до исполнителя с параметром «убавь».
«Сколько места на диске» уходило в модель, и та отвечала статьёй о том, как
посмотреть место на диске, — знать, сколько его здесь, она не может. Время
словами («в восемь вечера») не разбиралось вовсе: напоминание не ставилось, а
отложенная команда выполнялась немедленно.

Каждую заметили, когда она уже мешала жить. Набор фраз с ожидаемым разбором
даёт то, чего не хватало: число. Первый прогон дал 79,7%.

ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ ОСТАЛЬНЫХ ПРОВЕРОК. Те проверяют отдельные правила и
ловят поломку конкретного места. Эта отвечает на вопрос «стало лучше или хуже в
целом» — и показывает, что именно не понято, списком.

КАК ПОПОЛНЯТЬ. Промах здесь — находка, а не повод подогнать фразу под разбор.
Фразы пишутся так, как их ГОВОРЯТ: «сделай потише», а не «уменьшить громкость».
"""

import pytest

pytestmark = pytest.mark.unit

try:
    import accuracy
    import understanding
    from command_parser import CommandParser
    from fast_intent import get_fast_intent_engine
    from question_answerer import get_question_answerer
except ImportError:  # pragma: no cover — запуск из корня репозитория
    from backend import accuracy, understanding
    from backend.command_parser import CommandParser
    from backend.fast_intent import get_fast_intent_engine
    from backend.question_answerer import get_question_answerer


# Ниже этого значения работа считается сломанной.
#
# Не «сколько получилось», а «ниже чего опускаться нельзя»: порог, подогнанный
# под текущий результат, ломается от любой мелочи и приучает его подкручивать.
# Сейчас набор проходится целиком; девяносто пять процентов — запас на фразы,
# которые добавят после и не успеют починить.
ПОРОГ = 95.0


@pytest.fixture(scope="module")
def движки():
    """Настоящие движки разбора: подменять их здесь нечем и незачем."""
    return {
        "intent_engine": get_fast_intent_engine(),
        "parser": CommandParser(),
        "answerer": get_question_answerer(),
    }


@pytest.fixture(scope="module")
def итог(движки):
    return accuracy.check(understanding, движки)


def test_набор_не_пустой():
    """
    Проверка на саму проверку: пустой набор дал бы 0 из 0 и радостно прошёл.
    """
    assert len(accuracy.load_phrases()) >= 50


def test_точность_не_ниже_порога(итог):
    """
    Главное число. Упало — значит правка разбора сломала что-то соседнее, и
    список ниже покажет, что именно.
    """
    assert итог["точность"] >= ПОРОГ, "\n" + accuracy.report(итог)


def test_ни_одна_команда_не_стала_вопросом(итог):
    """
    Худший из промахов. Команда, ушедшая в модель, выглядит для человека как
    «Scott меня не понял»: он просил открыть браузер, а получил рассуждение о
    браузерах. Обратная ошибка заметнее и потому менее опасна.
    """
    потерянные = [п for п in итог["промахи"]
                  if п["вышло"].startswith("question")
                  and not п["ожидалось"].startswith("question")]

    assert not потерянные, "команды ушли в модель:\n" + "\n".join(
        f"  «{п['фраза']}» → {п['вышло']}" for п in потерянные)


def test_ни_один_вопрос_не_стал_командой(итог):
    """
    Пара к проверке выше. Вопрос, принятый за команду, — это Scott, который
    вместо ответа что-то делает: «чем открыть pdf» не должно ничего запускать.
    """
    исполненные = [п for п in итог["промахи"]
                   if п["ожидалось"].startswith("question")
                   and п["вышло"].startswith("action")]

    assert not исполненные, "вопросы стали командами:\n" + "\n".join(
        f"  «{п['фраза']}» → {п['вышло']}" for п in исполненные)
