"""
Озвучка длинного ответа по частям.

ЗАЧЕМ ЭТО СДЕЛАНО. Ответ синтезировался целиком, и только потом начинал
звучать. Замеры на живой машине: до 2,4 секунды между командой и первым словом
— секунды, в которые человек не знает, услышали его или нет. Именно это и
ощущается как медлительность Scott, хотя сама команда к тому времени давно
выполнена (медиана 3 миллисекунды).

ГЛАВНАЯ ЛОВУШКА, которую здесь и проверяем: промежуточные куски НЕЛЬЗЯ
дожидаться. Если ждать каждый, синтез следующего начнётся только после того,
как отзвучал предыдущий, — и вся затея сведётся к нулю, причём незаметно:
работать будет, звучать будет, а быстрее не станет.

Последний кусок, наоборот, дожидаться обязательно: слушатель держит микрофон
приостановленным всё время речи, иначе Scott услышит сам себя и примет свой
ответ за команду.
"""

import pytest

pytestmark = pytest.mark.unit

try:
    import scott_voice
except ImportError:  # pragma: no cover — запуск из корня репозитория
    from backend import scott_voice


class ПодставнойГолос:
    """
    Тот же speak, но без движка синтеза и без звука.

    Класс собирается без __init__ намеренно: настоящий поднимает pyttsx3, папку
    кэша и рабочий поток — всё это к разбиению ответа на куски отношения не
    имеет, а на машине проверок может и не работать.
    """

    def __init__(self):
        self.синтезировано = []
        self.проиграно = []

    speak = scott_voice.ScottVoice.speak

    def speak_to_file(self, text, voice=None):
        self.синтезировано.append(text)
        return f"файл-{len(self.синтезировано)}.wav"

    def play_audio(self, audio_file, force=False, wait=True):
        self.проиграно.append((audio_file, wait))


@pytest.fixture
def голос(monkeypatch):
    """Голос, который не молчит: тихий режим здесь проверяется отдельно."""
    try:
        import audio_settings
    except ImportError:  # pragma: no cover
        from backend import audio_settings

    monkeypatch.setattr(audio_settings, "is_quiet", lambda: False)
    return ПодставнойГолос()


ДЛИННЫЙ = ("Диск C заполнен на семьдесят процентов. Свободно сто двадцать гигабайт. "
           "Больше всего занимает папка загрузок. Могу открыть её.")


def test_длинный_ответ_синтезируется_частями(голос):
    голос.speak(ДЛИННЫЙ)

    assert len(голос.синтезировано) > 1


def test_первый_кусок_это_одно_предложение(голос):
    """Смысл всей затеи: начать говорить через одно предложение, а не через весь ответ."""
    голос.speak(ДЛИННЫЙ)

    assert голос.синтезировано[0] == "Диск C заполнен на семьдесят процентов."


def test_промежуточные_куски_не_дожидаются(голос):
    """
    Главная ловушка. Ожидание на промежуточном куске сводит всю затею на нет —
    и делает это незаметно: работать будет, а быстрее не станет.
    """
    голос.speak(ДЛИННЫЙ)

    ожидания = [ждать for _, ждать in голос.проиграно]

    assert ожидания[:-1] == [False] * (len(ожидания) - 1)


def test_последний_кусок_дожидается(голос):
    """
    Иначе слушатель вернёт микрофон в работу посреди речи, Scott услышит сам
    себя и примет свой ответ за новую команду.
    """
    голос.speak(ДЛИННЫЙ)

    assert голос.проиграно[-1][1] is True


def test_короткий_ответ_озвучивается_целиком(голос):
    """
    «Готово» делить нечего, и оно почти всегда уже в кэше озвученных реплик —
    разбиение только лишило бы его этого.
    """
    голос.speak("Готово.")

    assert голос.синтезировано == ["Готово."]
    assert голос.проиграно == [("файл-1.wav", True)]


def test_ничего_не_теряется(голос):
    """
    Самое важное: Scott должен произнести весь ответ. Потерянное предложение
    хуже задержки — о потере человек не узнает.
    """
    голос.speak(ДЛИННЫЙ)

    assert " ".join(голос.синтезировано) == ДЛИННЫЙ


def test_в_тихом_режиме_не_синтезируется_ничего(голос, monkeypatch):
    """
    Синтез занимает работу видеокарты ради звука, который никто не услышит, —
    и по частям это стало бы несколькими такими заходами вместо одного.
    """
    try:
        import audio_settings
    except ImportError:  # pragma: no cover
        from backend import audio_settings

    monkeypatch.setattr(audio_settings, "is_quiet", lambda: True)

    голос.speak(ДЛИННЫЙ)

    assert голос.синтезировано == []
    assert голос.проиграно == []
