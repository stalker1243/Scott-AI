"""
Проекты, над которыми человек работает.

Список сам по себе бесполезен — такой заводят в блокноте. Смысл появляется от
того, что Scott им пользуется: открывает папку по названию и держит текущий
проект в уме, отвечая на вопросы о работе.

Поэтому проверок здесь две породы. Первая — про хранение и пределы, обычная.
Вторая, важнее: про то, что «открой проект скотт» не уходит общему разбору
команд. Тот видит «открой» и принимается искать программу с названием «проект
скотт» — которой, разумеется, нет.

И отдельно — про папку. Удаление проекта не должно трогать её на диске: при
первой же опечатке это стоило бы человеку работы.
"""

import pytest

pytestmark = pytest.mark.unit

try:
    import projects
    import understanding
except ImportError:  # pragma: no cover — запуск из корня репозитория
    from backend import projects, understanding


@pytest.fixture
def хранилище(tmp_path, monkeypatch):
    monkeypatch.setattr(projects, "STORE_PATH", tmp_path / "projects.json")
    return projects


# ==================== Хранение ====================

def test_заведённый_проект_читается_обратно(хранилище, tmp_path):
    хранилище.add("ScottAI", path=str(tmp_path), stack="C#")

    список = хранилище.all_projects()

    assert len(список) == 1
    assert список[0]["name"] == "ScottAI"
    assert список[0]["stack"] == "C#"


def test_первый_проект_становится_текущим(хранилище):
    """Человек, добавивший один проект, уж точно работает над ним."""
    хранилище.add("Единственный")

    assert хранилище.current()["name"] == "Единственный"


def test_текущий_проект_только_один(хранилище):
    хранилище.add("Первый")
    второй = хранилище.add("Второй")["project"]

    хранилище.set_current(второй["id"])

    текущие = [п for п in хранилище.all_projects() if п["current"]]
    assert len(текущие) == 1
    assert текущие[0]["name"] == "Второй"


def test_текущий_показывается_первым(хранилище):
    """К нему обращаются чаще всего — искать его глазами человек не должен."""
    хранилище.add("Старый")
    новый = хранилище.add("Новый")["project"]
    хранилище.set_current(новый["id"])

    assert хранилище.all_projects()[0]["name"] == "Новый"


def test_проект_без_названия_не_заводится(хранилище):
    итог = хранилище.add("   ")

    assert not итог["success"]


def test_повтор_названия_отклоняется(хранилище):
    """
    Два проекта с одним именем нельзя различить голосом: «открой проект Scott»
    стало бы гаданием.
    """
    хранилище.add("ScottAI")
    итог = хранилище.add("scottai")

    assert not итог["success"]


def test_несуществующая_папка_не_мешает_завести_проект(хранилище):
    """
    Папку могли ещё не создать, а проект уже есть. Но сказать об этом стоит
    сразу, а не при первой попытке открыть.
    """
    итог = хранилище.add("Будущий", path="C:/такой-папки-нет-12345")

    assert итог["success"]
    assert "нет" in итог.get("note", "").lower()


def test_пропавшая_папка_видна_в_списке(хранилище):
    """Папку могли удалить или перенести уже после того, как проект завели."""
    хранилище.add("Переехавший", path="C:/такой-папки-нет-12345")

    assert хранилище.all_projects()[0]["exists"] is False


def test_испорченный_файл_не_роняет_запуск(хранилище):
    хранилище.STORE_PATH.parent.mkdir(parents=True, exist_ok=True)
    хранилище.STORE_PATH.write_text("не json вовсе", encoding="utf-8")

    assert хранилище.all_projects() == []


# ==================== Удаление ====================

def test_удаление_проекта_не_трогает_папку(хранилище, tmp_path):
    """
    Самое важное здесь. Scott перестаёт знать о проекте, работа остаётся на
    месте: обратное стоило бы человеку всего при первой же опечатке.
    """
    папка = tmp_path / "работа"
    папка.mkdir()
    (папка / "важное.txt").write_text("не трогать", encoding="utf-8")

    проект = хранилище.add("Работа", path=str(папка))["project"]
    хранилище.remove(проект["id"])

    assert папка.exists()
    assert (папка / "важное.txt").read_text(encoding="utf-8") == "не трогать"


def test_после_удаления_текущего_текущим_становится_другой(хранилище):
    """Иначе Scott перестал бы держать в уме хоть что-нибудь."""
    первый = хранилище.add("Первый")["project"]
    хранилище.add("Второй")

    хранилище.remove(первый["id"])

    assert хранилище.current() is not None


def test_удаление_несуществующего_не_ошибка_программы(хранилище):
    итог = хранилище.remove("такого-нет")

    assert not итог["success"]
    assert итог["error"]


# ==================== Поиск по названию ====================

def test_проект_находится_по_части_названия(хранилище):
    хранилище.add("ScottAI Remake")

    assert хранилище.find("scott")["name"] == "ScottAI Remake"


def test_русское_произношение_находит_латинское_название(хранилище):
    """
    Главное для голоса. Человек говорит «открой проект скотт», Whisper пишет
    это кириллицей, а проект называется ScottAI — прямое сравнение не находит
    ничего. Поймано на живой проверке: проект был заведён, а Scott отвечал «не
    знаю такого».
    """
    хранилище.add("ScottAI Remake")

    assert хранилище.find("скотт")["name"] == "ScottAI Remake"


def test_точное_совпадение_важнее_частичного(хранилище):
    хранилище.add("Сайт")
    хранилище.add("Сайт портфолио")

    assert хранилище.find("Сайт")["name"] == "Сайт"


# ==================== Просьба открыть ====================

@pytest.mark.parametrize("фраза,ожидается", [
    ("открой проект ScottAI", "ScottAI"),
    ("покажи проект сайт", "сайт"),
    ("перейди к проекту Учебный", "Учебный"),
])
def test_просьба_открыть_проект_узнаётся(фраза, ожидается):
    assert understanding.extract_project(фраза) == ожидается


@pytest.mark.parametrize("фраза", [
    "открой блокнот",          # обычная программа, не проект
    "открой проект",           # не сказано какой
    "что за проект",
])
def test_обычные_команды_не_отбираются(фраза):
    """
    Слово «проект» обязательно: без него «открой скотт» — просьба запустить
    программу, и отбирать её у обычного разбора нельзя.
    """
    assert understanding.extract_project(фраза) is None


# ==================== Дорога до модели ====================

def test_без_проектов_ничего_не_меняется(хранилище):
    assert хранилище.prompt_addition() == ""


def test_текущий_проект_доходит_до_модели(хранилище):
    """
    Ради этого всё и делалось: вопрос «как здесь сделать асинхронно» от
    человека, пишущего на C#, заслуживает ответа про C#.
    """
    хранилище.add("ScottAI", stack="C# и Avalonia")

    добавка = хранилище.prompt_addition()

    assert "ScottAI" in добавка
    assert "C#" in добавка


def test_в_модель_уходит_только_текущий(хранилище):
    """Перечислять все проекты значит платить за это в каждом вопросе."""
    хранилище.add("Текущий")
    хранилище.add("Другой")

    добавка = хранилище.prompt_addition()

    assert "Текущий" in добавка
    assert "Другой" not in добавка
