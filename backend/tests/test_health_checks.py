"""
Проверки состояния: что у Scott работает прямо сейчас.

Смысл этой страницы в том, чтобы человек, у которого «не работает», увидел, ЧТО
именно не работает. Значит опасны здесь две вещи.

Первая: упавшая проверка уносит остальные. Человек с отключённым микрофоном
имеет право узнать, что у него с ключом ИИ, — а увидел бы пустую страницу.

Вторая: всё подряд помечено красным. Отсутствие видеокарты — не поломка, а
обстоятельство: Scott работает, просто медленнее. Смешав это с настоящими
отказами, мы научили бы человека не обращать внимания на красное вовсе.
"""

import pytest

pytestmark = pytest.mark.unit

try:
    import health_checks
except ImportError:  # pragma: no cover — запуск из корня репозитория
    from backend import health_checks


# ==================== Устойчивость ====================

def test_упавшая_проверка_не_роняет_остальные(monkeypatch):
    """
    Ради этого каждая проверка и обёрнута.

    Микрофон может отсутствовать, библиотека — не установиться, устройство —
    отвалиться посреди опроса. Любой из этих случаев не должен лишать человека
    сведений обо всём остальном.
    """
    def взрыв():
        raise RuntimeError("устройство отвалилось")

    monkeypatch.setattr(health_checks, "ПРОВЕРКИ",
                        [("тест", "Взрывная", взрыв)] + health_checks.ПРОВЕРКИ)

    итог = health_checks.run_all()

    assert len(итог["checks"]) == len(health_checks.ПРОВЕРКИ)
    сломанная = итог["checks"][0]
    assert сломанная["state"] == health_checks.FAIL
    assert "устройство отвалилось" in сломанная["detail"]


def test_падение_проверки_объясняется_словами(monkeypatch):
    """«Проверить не удалось» полезнее, чем пустое место."""
    итог = health_checks._проверка("x", "Что-то", lambda: 1 / 0)

    assert итог["state"] == health_checks.FAIL
    assert "не удалось" in итог["detail"]


def test_у_каждой_проверки_есть_название_и_состояние():
    итог = health_checks.run_all()

    assert итог["checks"], "проверок не оказалось вовсе"

    for проверка in итог["checks"]:
        assert проверка["title"], f"у проверки {проверка['id']} нет названия"
        assert проверка["state"] in (health_checks.OK, health_checks.WARN, health_checks.FAIL)
        assert проверка.get("detail"), f"проверка {проверка['id']} ничего не объясняет"


# ==================== Итог ====================

def test_отказ_важнее_замечания(monkeypatch):
    """
    Один отказ делает итог отказом, сколько бы ни было замечаний рядом.

    Иначе человек с неработающим микрофоном прочёл бы «работает с оговорками» и
    пошёл искать неполадку в другом месте.
    """
    monkeypatch.setattr(health_checks, "ПРОВЕРКИ", [
        ("a", "Одно", lambda: {"state": health_checks.WARN, "detail": "так себе"}),
        ("b", "Другое", lambda: {"state": health_checks.FAIL, "detail": "совсем нет"}),
    ])

    assert health_checks.run_all()["state"] == health_checks.FAIL


def test_когда_всё_хорошо_так_и_сказано(monkeypatch):
    monkeypatch.setattr(health_checks, "ПРОВЕРКИ", [
        ("a", "Одно", lambda: {"state": health_checks.OK, "detail": "работает"}),
    ])

    итог = health_checks.run_all()

    assert итог["state"] == health_checks.OK
    assert "Всё работает" in итог["summary"]


def test_замечания_не_выдаются_за_поломку(monkeypatch):
    """
    Нет видеокарты — Scott работает, просто медленнее. Это не повод показывать
    человеку красное: увидев его там, где всё в порядке, он перестанет верить
    красному и там, где действительно сломано.
    """
    monkeypatch.setattr(health_checks, "ПРОВЕРКИ", [
        ("a", "Одно", lambda: {"state": health_checks.WARN, "detail": "медленно"}),
    ])

    assert health_checks.run_all()["state"] == health_checks.WARN


def test_отсутствие_видеокарты_не_считается_отказом():
    """
    Проверка живая, на этой машине. Каким бы ни был ответ, «нет видеокарты»
    отказом быть не должно.
    """
    итог = health_checks._проверка("gpu", "Видеокарта", health_checks._видеокарта)

    assert итог["state"] != health_checks.FAIL


def test_ненастроенная_модель_не_считается_отказом():
    """Команды Scott выполняет и без модели — красным это помечать не за что."""
    итог = health_checks._проверка("ai", "Модель ИИ", health_checks._модель_ии)

    assert итог["state"] != health_checks.FAIL


# ==================== Отчёт словами ====================

def test_отчёт_годится_для_пересылки():
    """
    Главный способ рассказать о поломке: вместо «у меня не работает» — список,
    по которому видно, что именно.
    """
    текст = health_checks.as_text()

    assert "Scott AI" in текст
    assert "Итог:" in текст

    # Каждая проверка — своей строкой, иначе смысла в пересылке нет.
    for проверка in health_checks.run_all()["checks"]:
        assert проверка["title"] in текст


def test_в_отчёте_нет_ключей(monkeypatch):
    """
    Отчёт пересылают. Ключ, попавший в него, уедет вместе с ним — и это
    худшее, чем может кончиться попытка попросить о помощи.
    """
    monkeypatch.setenv("GROQ_API_KEY", "gsk_совершенно_секретный_ключ")

    текст = health_checks.as_text()

    assert "gsk_совершенно_секретный_ключ" not in текст
