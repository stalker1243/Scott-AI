"""
Сборка программы для macOS.

Программа там — не файл, а папка со строгим устройством, и ошибки в нём
наказываются молчанием: система просто не запускает бандл или не показывает
запрос прав, а человек видит либо «повреждён», либо ничего.

Самое опасное здесь — права. Микрофон и управление другими программами
спрашиваются по тексту из Info.plist, и ровно один раз. Без строки про
микрофон запроса не будет вовсе: процесс убьют при первом обращении к нему,
без ошибки и без следа в логе. Пропажу такой строки не заметит ни сборка, ни
запуск на Windows — поэтому она проверяется здесь.

Сборщик вызывается по-настоящему, но без лаунчера: минута работы dotnet к
устройству бандла отношения не имеет.
"""

import plistlib
import struct
from pathlib import Path

import pytest

pytestmark = pytest.mark.unit

КОРЕНЬ = Path(__file__).resolve().parent.parent.parent
СБОРЩИК = КОРЕНЬ / "installer" / "build_macos.py"


@pytest.fixture(scope="module")
def бандл(tmp_path_factory):
    """
    Собранный ScottAI.app — один на все проверки этого файла.

    Зовётся та же функция, что и при настоящей сборке, — проверять сделанную
    вручную копию устройства бандла бессмысленно.
    """
    место = tmp_path_factory.mktemp("macos")

    import importlib.util

    spec = importlib.util.spec_from_file_location("build_macos", СБОРЩИК)
    модуль = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(модуль)

    модуль.DIST = место
    модуль.RELEASE = место / "release"

    return модуль.build_bundle(место / "arm64", "1.2.3", "osx-arm64", skip_launcher=True)


# ==================== Устройство ====================

def test_бандл_устроен_как_положено(бандл):
    """
    Исполняемый файл в MacOS, всё остальное в Resources.

    Не вкусовщина: подпись бандла считает посторонние файлы в MacOS/
    нарушением, и система откажется запускать программу.
    """
    assert (бандл / "Contents" / "MacOS" / "ScottAI").exists()
    assert (бандл / "Contents" / "Info.plist").exists()
    assert (бандл / "Contents" / "Resources").is_dir()


def test_backend_лежит_в_resources(бандл):
    """Там же, где его ищет лаунчер, — и не рядом с исполняемым файлом."""
    backend = бандл / "Contents" / "Resources" / "backend"

    assert (backend / "main.py").exists(), "в бандле нет backend"
    assert not (бандл / "Contents" / "MacOS" / "backend").exists(), (
        "backend положен рядом с исполняемым файлом — подпись такого не допустит")


def test_данные_машины_в_бандл_не_попадают(бандл):
    """
    Профили, история разговоров и логи принадлежат конкретному компьютеру.

    В дистрибутиве им делать нечего, а история разговоров — это ещё и личная
    переписка владельца.
    """
    backend = бандл / "Contents" / "Resources" / "backend"

    assert not (backend / "data").exists()
    assert not (backend / "logs").exists()
    assert not (backend / "__pycache__").exists()


# ==================== Права ====================

def описание(бандл) -> dict:
    return plistlib.loads((бандл / "Contents" / "Info.plist").read_bytes())


def test_права_на_микрофон_запрошены(бандл):
    """
    Без этой строки запроса не будет вовсе — процесс убьют при первом
    обращении к микрофону, молча.
    """
    текст = описание(бандл).get("NSMicrophoneUsageDescription", "")

    assert текст, "в Info.plist нет объяснения, зачем Scott микрофон"
    assert len(текст) > 20, "объяснение слишком короткое, чтобы что-то объяснить"


def test_права_на_управление_программами_запрошены(бандл):
    """
    Громкость, яркость и выключение идут через osascript. Без этой строки они
    перестанут работать — тоже молча.
    """
    assert описание(бандл).get("NSAppleEventsUsageDescription")


def test_объяснения_написаны_по_русски(бандл):
    """
    Человек увидит эти тексты в системном запросе. Scott говорит по-русски —
    и запрос должен тоже, иначе он выглядит как окно чужой программы.
    """
    for ключ in ("NSMicrophoneUsageDescription", "NSAppleEventsUsageDescription"):
        текст = описание(бандл)[ключ]
        assert any("а" <= буква.lower() <= "я" for буква in текст), (
            f"{ключ} написано не по-русски: {текст}")


# ==================== Описание ====================

def test_версия_попадает_в_бандл(бандл):
    """
    Без неё установленная программа считает свою версию нулевой и предлагает
    обновиться на ту, что уже стоит, — этим закончился выпуск 1.0.2.
    """
    assert описание(бандл)["CFBundleShortVersionString"] == "1.2.3"
    assert (бандл / "Contents" / "Resources" / "VERSION.json").exists()


def test_экраны_retina_учтены(бандл):
    """Иначе окно рисуется вчетверо крупнее и мутно."""
    assert описание(бандл)["NSHighResolutionCapable"] is True


def test_имя_исполняемого_файла_совпадает_с_описанием(бандл):
    """
    Расхождение здесь — это «программа повреждена» при запуске: система ищет
    файл по имени из Info.plist и не находит.
    """
    имя = описание(бандл)["CFBundleExecutable"]

    assert (бандл / "Contents" / "MacOS" / имя).exists()


# ==================== Значок ====================

def test_значок_собран_в_формате_macos(бандл):
    """
    Формат .icns собирается вручную: штатный iconutil есть только на Mac, а
    сборка идёт и с Windows. Проверяется заголовок — по нему система и узнаёт
    файл.
    """
    значок = бандл / "Contents" / "Resources" / "scott.icns"
    assert значок.exists(), "значка нет — бандл будет с системным"

    данные = значок.read_bytes()
    assert данные[:4] == b"icns"

    # В заголовке записана длина всего файла. Ошибка здесь — и значок не
    # прочитается вовсе.
    записано = struct.unpack(">I", данные[4:8])[0]
    assert записано == len(данные), (
        f"в заголовке {записано} байт, а в файле {len(данные)}")
