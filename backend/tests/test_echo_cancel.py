"""
Эхоподавление: Scott перестаёт слышать себя.

Микрофон слышит колонки, и собственный ответ возвращается как новая фраза. На
живой проверке это выглядело так: Scott произнёс ответ, а следующей строкой в
логе появилось «Мимо: "Попробую открыть Google Chrome"» — он распознал сам
себя.

ЗАМЕРЕНО на синтезированной речи с моделью комнаты (задержка, приглушение, два
отражения):

    эхо тише на          10–12 дБ
    голос человека тише  0.8 дБ
    расход времени       3% реального

ТРИ ОШИБКИ, найденные замером, и все три тихие — код работал, просто не делал
ничего полезного.

Первая: задержка искалась в обратную сторону. При задержке D запись отстаёт от
опорного сигнала, значит искать надо опорный ВНУТРИ записи. Перепутанное
направление давало ошибку от двадцати до ста восьмидесяти миллисекунд при
фильтре длиной шестнадцать — выравнивание не помогало вовсе.

Вторая: фильтр был вдвое короче нужного. Отражения от стен приходят через
десять-тридцать миллисекунд, а он охватывал шестнадцать.

Третья: защита от двойного разговора душила обучение. Она сравнивала остаток с
записью — «остаётся столько же, значит говорит человек», — но пока фильтр не
обучен, остаток и равен записи по определению. Из ста двадцати блоков
пропускалось сто, и подавление падало до четырёх десятых децибела.
"""

import numpy as np
import pytest

pytestmark = pytest.mark.unit


try:
    import echo_cancel
except ImportError:  # pragma: no cover — запуск из корня репозитория
    from backend import echo_cancel


ЧАСТОТА = 16000
БЛОК = 480          # 30 мс, как у слушателя


def речь(секунд=2.0, семя=1):
    """
    Звук, похожий на речь: шум, пропущенный через сглаживание.

    Настоящая речь здесь не нужна, а вот белый шум не годится: у него нет
    спектральной окраски, и любой фильтр справляется с ним подозрительно
    хорошо.
    """
    случай = np.random.default_rng(семя)
    сырьё = случай.standard_normal(int(ЧАСТОТА * секунд)).astype(np.float32)

    # Сглаживание убирает верхние частоты — получается нечто с огибающей,
    # похожей на голос.
    окно = np.hanning(64).astype(np.float32)
    окно /= окно.sum()
    сглажено = np.convolve(сырьё, окно, mode="same").astype(np.float32)

    # Огибающая: речь не звучит ровно, в ней есть слоги и паузы.
    слоги = np.abs(np.sin(np.linspace(0, секунд * 12, сглажено.size))) + 0.15
    return (сглажено * слоги * 0.3).astype(np.float32)


def эхо_от(сигнал, задержка_мс=120, громкость=0.5, комната=True):
    """Что услышит микрофон: задержанная, приглушённая, искажённая копия."""
    задержка = int(ЧАСТОТА * задержка_мс / 1000)
    эхо = np.zeros(len(сигнал) + задержка, dtype=np.float32)
    эхо[задержка:] = сигнал * громкость

    if комната:
        for сдвиг, сила in ((int(ЧАСТОТА * 0.013), 0.35),
                            (int(ЧАСТОТА * 0.027), 0.18)):
            хвост = np.zeros_like(эхо)
            хвост[сдвиг:] = эхо[:len(эхо) - сдвиг] * сила
            эхо = эхо + хвост

    return эхо


def прогнать(ушастик, запись, опорный):
    """Пропустить запись через подавление блоками, как в жизни."""
    куски = []
    for i in range(0, len(запись), БЛОК):
        куски.append(ушастик.process(запись[i:i + БЛОК], опорный[i:i + БЛОК]))
    return np.concatenate(куски)


def выровнять(опорный, задержка, длина):
    return np.concatenate([np.zeros(задержка, dtype=np.float32), опорный])[:длина]


# ==================== Задержка ====================

@pytest.mark.parametrize("задержка_мс", [40, 120, 250, 380])
def test_delay_is_found(задержка_мс):
    """
    Задержка находится точно.

    Между «отдали звук на воспроизведение» и «микрофон это услышал» проходит
    от сотни до нескольких сотен миллисекунд, и величина своя на каждой
    машине. Ошибка здесь обесценивает всё остальное: фильтр охватывает
    тридцать две миллисекунды и промах в сто не вытянет.
    """
    сигнал = речь(2.0)
    запись = эхо_от(сигнал, задержка_мс, комната=False)

    опорный = np.zeros_like(запись)
    опорный[:len(сигнал)] = сигнал

    найдено = echo_cancel.estimate_delay(запись, опорный, ЧАСТОТА)
    ожидалось = int(ЧАСТОТА * задержка_мс / 1000)

    ошибка_мс = abs(найдено - ожидалось) / ЧАСТОТА * 1000
    assert ошибка_мс < 5, f"ошибка {ошибка_мс:.0f} мс"


def test_delay_search_looks_the_right_way():
    """
    Опорный сигнал ищется внутри записи, а не наоборот.

    Ровно эта ошибка и была: при задержке D запись отстаёт от опорного
    сигнала, значит искать надо опорный ВНУТРИ записи. Перепутанное
    направление давало случайный максимум, и на трёх замерах ошибка вышла 21,
    188 и 59 миллисекунд.
    """
    сигнал = речь(2.0)
    задержка = int(ЧАСТОТА * 0.15)
    запись = эхо_от(сигнал, 150, комната=False)

    опорный = np.zeros_like(запись)
    опорный[:len(сигнал)] = сигнал

    найдено = echo_cancel.estimate_delay(запись, опорный, ЧАСТОТА)

    # При перепутанном направлении нашлось бы что угодно, только не это.
    assert abs(найдено - задержка) < ЧАСТОТА * 0.005


def test_silence_gives_no_delay():
    """
    На тишине задержки нет.

    Сдвинуть сигнал наугад хуже, чем не сдвигать вовсе: неверное выравнивание
    портит работу фильтра на всё время ответа.
    """
    тишина = np.zeros(ЧАСТОТА, dtype=np.float32)

    assert echo_cancel.estimate_delay(тишина, тишина, ЧАСТОТА) == 0
    assert echo_cancel.estimate_delay(речь(1.0), тишина, ЧАСТОТА) == 0


def test_empty_input_does_not_crash():
    пусто = np.zeros(0, dtype=np.float32)

    assert echo_cancel.estimate_delay(пусто, речь(1.0), ЧАСТОТА) == 0
    assert echo_cancel.estimate_delay(речь(1.0), пусто, ЧАСТОТА) == 0


# ==================== Подавление ====================

def test_echo_is_suppressed():
    """
    Эхо становится заметно тише.

    Десять децибел — это втрое по громкости. Не тишина, но именно столько и
    нужно, чтобы распознаватель перестал принимать ответ Scott за фразу
    человека.
    """
    сигнал = речь(3.0)
    задержка = int(ЧАСТОТА * 0.12)
    запись = эхо_от(сигнал, 120)

    опорный = np.zeros_like(запись)
    опорный[:len(сигнал)] = сигнал

    ушастик = echo_cancel.EchoCanceller()
    очищено = прогнать(ушастик, запись, выровнять(опорный, задержка, len(запись)))

    # Первые блоки фильтр учится — меряем там, где он уже подстроился.
    половина = len(запись) // 2
    подавление = echo_cancel.suppression_db(запись[половина:], очищено[половина:])

    assert подавление > 8, f"подавление всего {подавление:.1f} дБ"


def test_room_reflections_need_a_longer_filter():
    """
    Фильтр должен доставать до отражений комнаты.

    Они приходят через десять-тридцать миллисекунд. Фильтр на шестнадцать
    миллисекунд их не достаёт, и подавление падает — это и было замерено:
    тридцать семь децибел против двадцати шести.
    """
    assert echo_cancel.FILTER_TAPS / ЧАСТОТА >= 0.030


def test_human_voice_survives():
    """
    Голос человека остаётся, когда он говорит поверх ответа.

    Главная беда адаптивного фильтра: он принимает живую речь за ошибку
    предсказания и учится вычитать её. Без защиты голос проседал на девять
    децибел — почти наравне с эхом, то есть перебить Scott было бы нельзя.
    """
    ответ = речь(3.0, семя=1)
    человек = речь(1.2, семя=99) * 1.5

    задержка = int(ЧАСТОТА * 0.12)
    запись = эхо_от(ответ, 120)

    начало = len(запись) // 2
    сколько = min(len(человек), len(запись) - начало)
    запись[начало:начало + сколько] += человек[:сколько]

    опорный = np.zeros_like(запись)
    опорный[:len(ответ)] = ответ

    ушастик = echo_cancel.EchoCanceller()
    очищено = прогнать(ушастик, запись, выровнять(опорный, задержка, len(запись)))

    потеря = echo_cancel.suppression_db(запись[начало:начало + сколько],
                                        очищено[начало:начало + сколько])

    assert потеря < 5, f"голос человека потерял {потеря:.1f} дБ"


def test_echo_gain_is_measured():
    """
    Усиление эха оценивается по ходу разговора.

    На нём и держится защита: ожидаемую громкость эха не с чем сравнивать,
    пока она неизвестна. Величина своя на каждой машине — зависит от
    громкости, расстояния до микрофона и его чувствительности.
    """
    сигнал = речь(3.0)
    задержка = int(ЧАСТОТА * 0.12)

    for громкость in (0.3, 0.5, 0.7):
        запись = эхо_от(сигнал, 120, громкость=громкость, комната=False)

        опорный = np.zeros_like(запись)
        опорный[:len(сигнал)] = сигнал

        ушастик = echo_cancel.EchoCanceller()
        прогнать(ушастик, запись, выровнять(опорный, задержка, len(запись)))

        assert abs(ушастик.echo_gain - громкость) < 0.15, \
            f"при громкости {громкость} оценили {ушастик.echo_gain:.2f}"


def test_learning_is_not_frozen_from_the_start():
    """
    Защита не должна душить обучение.

    Именно это и случилось в первой версии: она сравнивала остаток с записью,
    а пока фильтр не обучен, остаток равен записи по определению. Из ста
    двадцати блоков пропускалось сто.
    """
    сигнал = речь(3.0)
    задержка = int(ЧАСТОТА * 0.12)
    запись = эхо_от(сигнал, 120)

    опорный = np.zeros_like(запись)
    опорный[:len(сигнал)] = сигнал

    ушастик = echo_cancel.EchoCanceller()
    прогнать(ушастик, запись, выровнять(опорный, задержка, len(запись)))

    доля = ушастик.skipped / max(1, ушастик.blocks)
    assert доля < 0.3, f"пропущено {доля:.0%} блоков, фильтру некогда учиться"


# ==================== Устойчивость ====================

def test_silent_reference_leaves_recording_alone():
    """
    Scott молчит — вычитать нечего.

    Трогать фильтр на тишине нельзя: он только расшатается, а первый же
    настоящий блок придётся начинать заново.
    """
    ушастик = echo_cancel.EchoCanceller()
    запись = речь(0.5)
    тишина = np.zeros_like(запись)

    очищено = ушастик.process(запись, тишина)

    assert np.allclose(очищено, запись)
    assert ушастик.blocks == 0


def test_short_reference_is_padded():
    """
    Ответ Scott кончился раньше блока.

    Обычный случай на последнем блоке: опорного сигнала меньше, чем записи, и
    хвост дополняется тишиной.
    """
    ушастик = echo_cancel.EchoCanceller()
    запись = речь(0.1)
    короткий = речь(0.05)

    очищено = ушастик.process(запись, короткий)

    assert len(очищено) == len(запись)


def test_reset_forgets_the_room():
    """
    Между ответами настройка сбрасывается.

    За паузу могли поменять громкость, переставить колонки или сменить
    устройство вывода — прежние коэффициенты станут не улучшать, а портить.
    """
    сигнал = речь(1.0)
    ушастик = echo_cancel.EchoCanceller()

    прогнать(ушастик, эхо_от(сигнал, 0, комната=False)[:len(сигнал)], сигнал)
    assert ушастик.blocks > 0

    ушастик.reset()

    assert ушастик.blocks == 0
    assert ушастик.echo_gain == 0
    assert not ушастик.weights.any()


def test_processing_is_fast_enough():
    """
    Обработка должна укладываться в реальное время с большим запасом.

    Она идёт на каждом блоке микрофона, параллельно с распознаванием и
    синтезом. Замерено: около трёх процентов реального времени.

    Порог стоит с двукратным запасом к реальному времени, а не вплотную к
    замеренному. Проверяется свойство алгоритма — успевает ли он в принципе, —
    а на занятой машине замер говорит прежде всего о занятости машины: при
    полном прогоне тестов, когда рядом считают другие проверки, те же три
    процента превращались в двадцать восемь, и проверка падала на ровном месте.
    Настоящую же беду — скажем, впятеро подорожавшую обработку — такой порог
    поймает всё равно.

    Берётся лучший из нескольких замеров по той же причине.
    """
    import time

    сигнал = речь(3.0)
    задержка = int(ЧАСТОТА * 0.12)
    запись = эхо_от(сигнал, 120)

    опорный = np.zeros_like(запись)
    опорный[:len(сигнал)] = сигнал
    выровненный = выровнять(опорный, задержка, len(запись))

    длительность = len(запись) / ЧАСТОТА
    лучшая = float("inf")

    for _ in range(3):
        ушастик = echo_cancel.EchoCanceller()

        часы = time.perf_counter()
        прогнать(ушастик, запись, выровненный)
        прошло = time.perf_counter() - часы

        лучшая = min(лучшая, прошло / длительность)

    assert лучшая < 0.5, f"обработка занимает {лучшая:.0%} реального времени"


def test_suppression_db_reads_plainly():
    тихий = np.full(100, 0.1, dtype=np.float32)
    громкий = np.full(100, 1.0, dtype=np.float32)

    # Вдесятеро тише — это двадцать децибел.
    assert abs(echo_cancel.suppression_db(громкий, тихий) - 20) < 0.5

    # Ничего не изменилось — ноль.
    assert abs(echo_cancel.suppression_db(громкий, громкий)) < 0.01
