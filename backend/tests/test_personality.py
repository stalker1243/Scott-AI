"""
Персонализация: характер Scott и то, что он знает о своём человеке.

Раньше это была видимость. В лаунчере стояло поле «О себе», оно сохранялось —
и оставалось в настройках лаунчера: на backend не уходило, в разговор не
попадало. Человек писал «я программист, пишу на C#», а Scott отвечал ровно так
же, как всем. В профиле лежал ключ personality со значением «professional», и
не читал его никто.

Поэтому главная проверка здесь — не «сохранилось ли», а «дошло ли до модели».
Сохранить настройку легко; незаметно потерять её по дороге к запросу — ещё
легче, и снаружи это выглядит как «Scott меня не слушает».
"""

import json

import pytest

pytestmark = pytest.mark.unit

try:
    import personality
except ImportError:  # pragma: no cover — запуск из корня репозитория
    from backend import personality


@pytest.fixture
def настройки(tmp_path, monkeypatch):
    """Персонализация со своим файлом — чтобы не трогать настоящие."""
    monkeypatch.setattr(personality, "CONFIG_PATH", tmp_path / "personality.json")
    return personality


# ==================== Хранение ====================

def test_по_умолчанию_ничего_не_настроено(настройки):
    данные = настройки.load()

    assert данные["about"] == ""
    assert данные["interests"] == []
    assert данные["style"] == настройки.DEFAULT_STYLE


def test_сохранённое_читается_обратно(настройки):
    настройки.save({
        "style": "brief",
        "about": "Пишу на C# и Python",
        "interests": ["программирование", "музыка"],
        "name": "Фантом",
    })

    данные = настройки.load()

    assert данные["style"] == "brief"
    assert данные["about"] == "Пишу на C# и Python"
    assert данные["interests"] == ["программирование", "музыка"]
    assert данные["name"] == "Фантом"


def test_испорченный_файл_не_роняет_запуск(настройки):
    """
    Настройки читаются при каждом ответе. Падение здесь означало бы, что Scott
    перестал отвечать вовсе — из-за строки в файле, которую человек, может
    быть, правил руками.
    """
    настройки.CONFIG_PATH.parent.mkdir(parents=True, exist_ok=True)
    настройки.CONFIG_PATH.write_text("{это не json", encoding="utf-8")

    данные = настройки.load()

    assert данные["style"] == настройки.DEFAULT_STYLE


def test_неизвестный_характер_заменяется_обычным(настройки):
    """
    Настройки переживают обновления программы. Характер, который был и пропал,
    не должен оставлять Scott без указаний вовсе.
    """
    сохранено = настройки.save({"style": "такого-характера-нет"})

    assert сохранено["style"] == настройки.DEFAULT_STYLE


# ==================== Пределы ====================

def test_рассказ_о_себе_обрезается(настройки):
    """
    Он уходит в КАЖДЫЙ запрос. Человек, вставивший туда страницу текста, платил
    бы за неё в каждом вопросе, а на маленькой бесплатной модели просто упёрся
    бы в предел длины — и Scott перестал бы отвечать.
    """
    сохранено = настройки.save({"about": "а" * 5000})

    assert len(сохранено["about"]) == настройки.MAX_ABOUT


def test_интересы_не_копятся_бесконечно(настройки):
    сохранено = настройки.save({"interests": [f"интерес {n}" for n in range(100)]})

    assert len(сохранено["interests"]) == настройки.MAX_INTERESTS


def test_повторы_среди_интересов_убираются(настройки):
    сохранено = настройки.save({"interests": ["музыка", "музыка", "кино"]})

    assert сохранено["interests"] == ["музыка", "кино"]


def test_пустые_интересы_отбрасываются(настройки):
    сохранено = настройки.save({"interests": ["", "   ", "кино"]})

    assert сохранено["interests"] == ["кино"]


# ==================== Дорога до модели ====================
#
# Ради этого всё и делалось. Сохранить настройку легко; незаметно потерять её
# по дороге к запросу — ещё легче, и снаружи это выглядит как «Scott меня не
# слушает».

def test_ненастроенная_персонализация_ничего_не_меняет(настройки):
    """
    Человек, не трогавший персонализацию, должен получать ровно прежнее
    поведение — без единого лишнего слова в указании модели.
    """
    assert настройки.prompt_addition() == ""


def test_рассказ_о_себе_доходит_до_модели(настройки):
    настройки.save({"about": "Я пишу на C# и веду свой проект"})

    добавка = настройки.prompt_addition()

    assert "C#" in добавка


def test_имя_доходит_до_модели(настройки):
    настройки.save({"name": "Фантом"})

    assert "Фантом" in настройки.prompt_addition()


def test_интересы_доходят_до_модели(настройки):
    настройки.save({"interests": ["астрономия"]})

    assert "астрономия" in настройки.prompt_addition()


def test_характер_доходит_до_модели(настройки):
    настройки.save({"style": "brief"})

    добавка = настройки.prompt_addition()

    assert добавка, "выбранный характер не дошёл до модели"
    assert настройки.STYLES["brief"]["prompt"] in добавка


def test_тон_описывается_последним(настройки):
    """
    Сначала — к кому обращаться и что о нём известно, и только потом, как
    говорить. Длинное рассуждение о тоне, поставленное первым, оттесняет из
    внимания модели то, что человек спросил, и ответ выходит вежливым, но
    бесполезным.
    """
    настройки.save({"style": "witty", "name": "Фантом", "about": "люблю кино"})

    добавка = настройки.prompt_addition()

    assert добавка.index("Фантом") < добавка.index(настройки.STYLES["witty"]["prompt"])


def test_персонализация_не_отменяет_основных_правил():
    """
    Добавка идёт ПОСЛЕ основных указаний и не заменяет их: характер меняет тон,
    а не обязанности. Иначе «отвечай коротко» стало бы способом обойти всё
    остальное, включая осторожность с опасными действиями.
    """
    try:
        import intelligent_answerer
    except ImportError:  # pragma: no cover
        from backend import intelligent_answerer

    источник = intelligent_answerer.IntelligentAnswerer.instructions.__doc__ or ""
    assert "ПОСЛЕ" in источник or "после" in источник

    # И по существу: основа остаётся целиком.
    ответчик = object.__new__(intelligent_answerer.IntelligentAnswerer)
    ответчик.system_prompt = "ОСНОВНЫЕ ПРАВИЛА"

    указание = intelligent_answerer.IntelligentAnswerer.instructions(ответчик)

    assert указание.startswith("ОСНОВНЫЕ ПРАВИЛА")


# ==================== Для интерфейса ====================

def test_список_характеров_отдаётся_целиком(настройки):
    """
    Лаунчер не должен знать характеры наизусть: добавленный здесь не появился
    бы в интерфейсе до пересборки программы.
    """
    описание = настройки.describe()

    assert len(описание["styles"]) == len(настройки.STYLES)
    for характер in описание["styles"]:
        assert характер["title"], "у характера нет названия"
        assert характер["hint"], "у характера нет пояснения"
