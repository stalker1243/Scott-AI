"""
Удалённый доступ: кто может командовать Scott издалека и что ему позволено.

Самое опасное место проекта. Голос требует присутствия: человек у микрофона
видит, что происходит, и может остановить. Команда издалека приходит в пустую
комнату — остановить её некому, и если канал окажется чужим, чужой получит
компьютер.

Отсюда и проверки. Они не про удобство, а про три вещи, каждая из которых при
ошибке стоит дорого: без привязки не командуют, разрешено меньше, чем Scott
умеет вообще, и всё выполненное остаётся в журнале.
"""

import time

import pytest

pytestmark = pytest.mark.unit

try:
    import remote_access
except ImportError:  # pragma: no cover — запуск из корня репозитория
    from backend import remote_access


@pytest.fixture
def доступ(tmp_path, monkeypatch):
    """Удалённый доступ со своими файлами — настоящие привязки не трогаем."""
    monkeypatch.setattr(remote_access, "STORE_PATH", tmp_path / "remote.json")
    monkeypatch.setattr(remote_access, "LOG_PATH", tmp_path / "log.json")
    monkeypatch.setattr(remote_access, "_pairing", None)
    monkeypatch.setattr(remote_access, "_recent", {})
    return remote_access


# ==================== Что позволено ====================

@pytest.mark.parametrize("действие", ["open_app", "question", "reminder", "search"])
def test_безобидное_позволено(доступ, действие):
    assert доступ.is_allowed(действие)


@pytest.mark.parametrize("действие", [
    "shutdown",        # на компьютере может идти работа
    "delete_file",     # отменить будет нельзя
    "close_app",       # в программе может быть несохранённое
    "powershell",      # произвольная команда оболочки
    "run_code",
])
def test_опасное_запрещено(доступ, действие):
    assert not доступ.is_allowed(действие)


def test_незнакомое_действие_запрещено(доступ):
    """
    Белый список, а не чёрный. Перечислить опасное невозможно: Scott умеет
    запускать программы, а значит умеет запустить что угодно. Перечислимо
    только безопасное — поэтому всё, чего нет в списке, запрещено.
    """
    assert not доступ.is_allowed("какое-то_новое_умение")


def test_отказ_объясняет_причину(доступ):
    """
    «Нельзя» без причины выглядит капризом программы. Человек за сотню
    километров должен понять, почему Scott отказался, и что делать.
    """
    причина = доступ.refusal("shutdown")

    assert len(причина) > 30
    assert "работа" in причина or "не делаю" in причина


# ==================== Привязка ====================

def test_без_кода_не_привязаться(доступ):
    """Главная защита: команда принимается только от привязанного устройства."""
    итог = доступ.pair("123456", "Телефон", channel="telegram", address="42")

    assert not итог["success"]
    assert доступ.devices() == []


def test_привязка_по_коду_работает(доступ):
    код = доступ.start_pairing()["code"]

    итог = доступ.pair(код, "Телефон", channel="telegram", address="42")

    assert итог["success"]
    assert len(доступ.devices()) == 1


def test_неверный_код_отклоняется(доступ):
    доступ.start_pairing()

    итог = доступ.pair("000000", "Чужой", channel="telegram", address="66")

    assert not итог["success"]
    assert доступ.devices() == []


def test_код_живёт_недолго(доступ, monkeypatch):
    """
    Минута — ровно столько, сколько нужно, чтобы прочитать код с экрана.
    Живущий час успевает попасть на фотографию экрана и в чужие глаза.
    """
    код = доступ.start_pairing()["code"]

    # Перематываем часы на две минуты вперёд. Именно time.time, а не monotonic:
    # шкалы разные, и подмена одной другой даёт время «в прошлом».
    потом = time.time() + 120
    monkeypatch.setattr(time, "time", lambda: потом)

    assert not доступ.pairing_active()
    assert not доступ.pair(код, "Опоздавший", channel="telegram", address="42")["success"]


def test_одним_кодом_привязывается_одно_устройство(доступ):
    """
    Иначе подсмотревший код успел бы привязать и своё — тем же кодом, пока тот
    не истёк.
    """
    код = доступ.start_pairing()["code"]
    доступ.pair(код, "Мой телефон", channel="telegram", address="42")

    итог = доступ.pair(код, "Чужой телефон", channel="telegram", address="66")

    assert not итог["success"]
    assert len(доступ.devices()) == 1


def test_новый_код_отменяет_прежний(доступ):
    первый = доступ.start_pairing()["code"]
    доступ.start_pairing()

    assert not доступ.pair(первый, "Телефон", channel="telegram", address="42")["success"]


# ==================== Отвязка ====================

def test_отвязанное_устройство_перестаёт_быть_своим(доступ):
    """
    Единственная защита при потерянном телефоне, поэтому действует немедленно.
    """
    код = доступ.start_pairing()["code"]
    устройство = доступ.pair(код, "Потерянный", channel="telegram", address="42")["device"]

    assert доступ.forget(устройство["id"])["success"]
    assert доступ.find_by_address("telegram", "42") is None


def test_ключ_устройства_наружу_не_показывается(доступ):
    """
    В списке устройств ключа быть не должно: его показывают только один раз,
    тому, кто привязывается.
    """
    код = доступ.start_pairing()["code"]
    доступ.pair(код, "Телефон", channel="telegram", address="42")

    assert all("token" not in у for у in доступ.devices())


# ==================== Частота ====================

def test_слишком_частые_команды_отсекаются(доступ):
    """
    Защита не от злого умысла, а от заклинившей кнопки и повторов при плохой
    связи: двадцать одинаковых «открой браузер» подряд человек не имел в виду.
    """
    for _ in range(доступ.RATE_LIMIT_PER_MINUTE):
        assert доступ.within_rate_limit("устройство")

    assert not доступ.within_rate_limit("устройство")


def test_ограничение_считается_для_каждого_устройства_отдельно(доступ):
    for _ in range(доступ.RATE_LIMIT_PER_MINUTE):
        доступ.within_rate_limit("первое")

    assert доступ.within_rate_limit("второе")


# ==================== Журнал ====================

def test_выполненное_издалека_попадает_в_журнал(доступ):
    """
    Без журнала о чужой команде не узнать никогда: она выполнится в пустой
    комнате и не оставит следа.
    """
    доступ.log("устройство", "Телефон", "открой браузер", "Открыл")

    записи = доступ.read_log()

    assert len(записи) == 1
    assert записи[0]["text"] == "открой браузер"
    assert записи[0]["device"] == "Телефон"


def test_отказы_тоже_записываются(доступ):
    """
    Попытка выключить компьютер издалека — именно то, о чём стоит узнать, даже
    если она не удалась.
    """
    доступ.log("устройство", "Телефон", "выключи компьютер", "отказано: shutdown")

    assert "отказано" in доступ.read_log()[0]["outcome"]


def test_журнал_не_растёт_бесконечно(доступ):
    for n in range(доступ.MAX_LOG + 50):
        доступ.log("у", "Телефон", f"команда {n}", "ок")

    assert len(доступ.read_log()) == доступ.MAX_LOG


def test_испорченное_хранилище_означает_никто_не_привязан(доступ):
    """
    Безопасный исход при испорченном файле — «никто не привязан», а не
    «привязаны все». Scott продолжит работать, просто перестанет слушаться
    издалека.
    """
    доступ.STORE_PATH.parent.mkdir(parents=True, exist_ok=True)
    доступ.STORE_PATH.write_text("не json", encoding="utf-8")

    assert доступ.devices() == []
    assert доступ.find_by_address("telegram", "42") is None
