"""
Scott AI - Расширенная база ответов
Дополнительные возможности и функции ассистента
"""

# === РАСШИРЕННАЯ БАЗА ЗНАНИЙ ===

EXTENDED_RESPONSES = {
    # Общие вопросы про Scott
    'who_are_you': {
        'patterns': [
            r'^\s*кто\s+ты\b', r'как\s+тебя\s+зовут', r'^\s*кто\s+такой\s+скотт',
            r'who\s+are\s+you', r'your\s+name'
        ],
        'responses': [
            'Я Scott AI - твой личный ИИ-ассистент. Я помогаю с вопросами, управляю командами и анализирую информацию.',
            'Я Scott - умный помощник, готовый помочь с любыми вопросами и задачами на компьютере.',
        ]
    },
    
    # Что ты умеешь
    'capabilities': {
        'patterns': [
            r'^\s*что\s+ты\s+умеешь\b', r'^\s*что\s+ты\s+можешь\b', r'^\s*какие\s+возможности\b',
            r'^\s*что\s+ты\s+делаешь\b', r'^\s*расскажи\s+про\s+свои\s+возможности\b',
            r'^\s*what\s+can\s+you\s+do\b', r'\bcapabilities\b'
        ],
        'responses': [
            '''Я могу:
- Отвечать на вопросы и объяснять сложные концепции
- Управлять приложениями и файлами на компьютере
- Получать информацию из интернета (курсы валют, погода, новости)
- Выполнять системные команды
- Говорить голосом
- Запоминать наши разговоры
- Помогать с программированием и техническими вопросами
- Многое другое!''',
        ]
    },
    
    # ВАЖНО про состав этого словаря.
    #
    # Раньше здесь были ещё категории programming / math / science / history / help.
    # Они ловили вопрос по ЛЮБОМУ упоминанию темы (r'\bpython\b', r'физика',
    # r'история', r'не знаю', ...) и возвращали общую фразу про всю категорию,
    # не отвечая на сам вопрос: «Расскажи про язык программирования Rust» →
    # «Язык программирования - это инструмент для создания программ».
    #
    # Поскольку эта база проверяется САМОЙ ПЕРВОЙ (до базы знаний и до LLM),
    # такие отписки перехватывали почти любой содержательный вопрос и не давали
    # ему дойти до модели — Scott выглядел глупее, чем он есть.
    #
    # Оставлены только категории, которые действительно отвечают по существу:
    # рассказ о себе, список возможностей и два динамических запроса к системе.
    # Всё остальное лучше отдать LLM, которая ответит на конкретный вопрос.

    # Время. Паттерны намеренно узкие: раньше здесь было просто r'время',
    # из-за чего «сколько времени занимает перелёт в Москву» отвечало текущим
    # временем на компьютере.
    'time': {
        'patterns': [
            # Якорь конца строки обязателен: без него «сколько времени занимает
            # перелёт в Токио» отвечало текущим временем на компьютере.
            r'который\s+час', r'сколько\s+(?:сейчас\s+)?времени\s*[?!.]*\s*$',
            r'текущее\s+время', r'^\s*время\s*[?!.]*\s*$',
            r'what\s+time', r'current\s+time', r'time\s+now'
        ],
        'is_dynamic': True,
        'handler': 'get_time'
    },

    # Система. Тоже сужено: прежние r'система', r'память', r'процессор' ловили
    # любые вопросы про память человека, историю процессоров и т.п. и выдавали
    # в ответ загрузку CPU.
    'system_info': {
        'patterns': [
            r'статус\s+системы', r'информаци[яию]\s+о\s+компьютере',
            r'состояние\s+компьютера', r'загрузк[аи]\s+(?:процессора|cpu)',
            r'сколько\s+(?:занято|свободно|осталось)\s+пам[яи]ти',
            r'system\s+info', r'computer\s+info'
        ],
        'is_dynamic': True,
        'handler': 'get_system_info'
    },
}

# === ВСПОМОГАТЕЛЬНЫЕ ФУНКЦИИ ===

import datetime
import psutil

def get_time():
    """Получить текущее время"""
    now = datetime.datetime.now()
    return f"Сейчас {now.strftime('%H:%M:%S')} (время на компьютере)"

def get_system_info():
    """Получить информацию о системе"""
    try:
        cpu_percent = psutil.cpu_percent(interval=1)
        memory = psutil.virtual_memory()
        disk = psutil.disk_usage('/')
        
        return f"""Статус компьютера:
- Процессор: {cpu_percent}%
- Памяти используется: {memory.percent}% ({memory.used // (1024**3)} GB из {memory.total // (1024**3)} GB)
- Место на диске: {disk.used // (1024**3)} GB использовано из {disk.total // (1024**3)} GB (свободно {disk.free // (1024**3)} GB)
"""
    except Exception as e:
        return f"Не смог получить информацию о системе: {e}"

# === ИНТЕГРАЦИЯ В QUESTION_ANSWERER ===

def try_extended_answer(text):
    """
    Попытаться найти ответ в расширенной базе
    
    Args:
        text: Текст вопроса
        
    Returns:
        Ответ или None
    """
    import re
    import random
    
    text_lower = text.lower()
    
    # Проверяем категории в правильном порядке (специфичные первыми)
    category_order = [
        'capabilities',  # Сначала специфичные "что ты умеешь"
        'time',          # Динамическое время
        'system_info',   # Динамическая информация системы
        'who_are_you',   # В конце общие вопросы про Scott
    ]
    
    for category in category_order:
        if category not in EXTENDED_RESPONSES:
            continue
            
        data = EXTENDED_RESPONSES[category]
        patterns = data.get('patterns', [])
        
        for pattern in patterns:
            if re.search(pattern, text_lower):
                # Если это динамический ответ
                if data.get('is_dynamic'):
                    handler_name = data.get('handler')
                    if handler_name == 'get_time':
                        return get_time()
                    elif handler_name == 'get_system_info':
                        return get_system_info()
                
                # Иначе возвращаем случайный ответ из списка
                responses = data.get('responses', [])
                if responses:
                    return random.choice(responses)
    
    return None
