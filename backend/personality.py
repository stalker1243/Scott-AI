"""
Каким Scott разговаривает и что он знает о своём человеке.

До этого персонализация была видимостью. В лаунчере стояло поле «О себе», оно
сохранялось — и оставалось лежать в настройках лаунчера: на backend не уходило
вовсе, в разговор не попадало. Человек писал «я программист, пишу на C#», а
Scott отвечал ровно так же, как всем. В профиле Scott лежал ключ personality со
значением «professional», и его не читал никто.

Здесь это становится настоящим: выбранный характер и рассказ о себе
подмешиваются к системному указанию модели — той самой строке, которая задаёт
её поведение в каждом ответе.

ЧТО ВАЖНО ПРИ ПРАВКАХ

Добавка идёт ПОСЛЕ основных правил и не может их отменить: характер меняет тон,
а не обязанности. Иначе «отвечай коротко» превратилось бы в способ обойти
запрет на опасные действия.

Рассказ о себе обрезается. Он уходит в каждый запрос, и человек, вставивший
туда страницу текста, платил бы за неё в каждом вопросе — а на маленьких
бесплатных моделях просто упёрся бы в предел длины.
"""

from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Dict, List

CONFIG_PATH = Path(__file__).resolve().parent / "data" / "personality.json"

# Сколько знаков о себе уходит в каждый запрос.
#
# Триста — это абзац: достаточно, чтобы сказать, кто вы и чем заняты, и мало,
# чтобы заметно удорожить каждый вопрос. Предел стоит здесь, а не в интерфейсе:
# запись может прийти и другим путём.
MAX_ABOUT = 300

# Сколько интересов учитывать.
MAX_INTERESTS = 12
MAX_INTEREST_LENGTH = 40


# Характеры.
#
# Каждый — не название, а указание модели, как говорить. Формулировки короткие
# намеренно: длинные инструкции о тоне вытесняют из внимания модели то, что
# человек спросил, и ответ становится вежливым, но бесполезным.
STYLES: Dict[str, Dict[str, str]] = {
    "friendly": {
        "title": "Дружелюбный",
        "hint": "Говорит просто и тепло, как хороший знакомый",
        "prompt": "Говори тепло и просто, как хороший знакомый. Без официальности.",
    },
    "business": {
        "title": "Деловой",
        "hint": "Сдержанно и по делу, без лишних слов",
        "prompt": "Говори сдержанно и по делу. Без шуток и лишних вступлений.",
    },
    "brief": {
        "title": "Краткий",
        "hint": "Отвечает одной-двумя фразами, когда это возможно",
        "prompt": (
            "Отвечай как можно короче — одной-двумя фразами, если вопрос это "
            "допускает. Подробности давай, только когда без них ответ будет неверным."
        ),
    },
    "butler": {
        "title": "Церемонный",
        "hint": "Обращается на «вы» и говорит с достоинством",
        "prompt": (
            "Обращайся на «вы», говори с достоинством и сдержанной любезностью, "
            "без подобострастия."
        ),
    },
    "witty": {
        "title": "С юмором",
        "hint": "Не прочь пошутить, но дело делает",
        "prompt": (
            "Можешь пошутить, если уместно, но сперва ответь по существу. "
            "Шутка не заменяет ответ."
        ),
    },
}

DEFAULT_STYLE = "friendly"


def _пусто() -> Dict:
    return {"style": DEFAULT_STYLE, "about": "", "interests": [], "name": ""}


def load() -> Dict:
    """
    Прочитать настройки. Испорченный файл не повод падать при старте.
    """
    try:
        if CONFIG_PATH.exists():
            данные = json.loads(CONFIG_PATH.read_text(encoding="utf-8"))
            if isinstance(данные, dict):
                return _причесать(данные)
    except Exception:
        pass
    return _пусто()


def _причесать(данные: Dict) -> Dict:
    """Привести к тому, с чем можно работать, что бы ни лежало в файле."""
    стиль = str(данные.get("style", DEFAULT_STYLE))
    if стиль not in STYLES:
        стиль = DEFAULT_STYLE

    about = str(данные.get("about", "") or "").strip()[:MAX_ABOUT]
    name = str(данные.get("name", "") or "").strip()[:60]

    интересы: List[str] = []
    for пункт in данные.get("interests", []) or []:
        текст = str(пункт or "").strip()[:MAX_INTEREST_LENGTH]
        if текст and текст not in интересы:
            интересы.append(текст)

    return {
        "style": стиль,
        "about": about,
        "interests": интересы[:MAX_INTERESTS],
        "name": name,
    }


def save(данные: Dict) -> Dict:
    """Сохранить и вернуть то, что действительно записано."""
    готово = _причесать(данные)

    CONFIG_PATH.parent.mkdir(parents=True, exist_ok=True)
    CONFIG_PATH.write_text(json.dumps(готово, ensure_ascii=False, indent=2), encoding="utf-8")

    return готово


def describe() -> Dict:
    """Настройки вместе со списком доступных характеров — для интерфейса."""
    текущее = load()
    return {
        **текущее,
        "styles": [
            {"id": ключ, "title": значение["title"], "hint": значение["hint"]}
            for ключ, значение in STYLES.items()
        ],
    }


def prompt_addition() -> str:
    """
    Добавка к системному указанию модели.

    Пустая строка означает «ничего не менять»: человек, не трогавший
    персонализацию, должен получать ровно прежнее поведение.

    Порядок частей не случаен. Сначала — к кому обращаться, потом — что о нём
    известно, и только потом — как говорить: тон описывается последним, чтобы
    не оттеснить собой содержательное.
    """
    данные = load()
    части: List[str] = []

    if данные["name"]:
        части.append(f"Человека, с которым ты говоришь, зовут {данные['name']}.")

    if данные["about"]:
        части.append(f"Вот что он рассказал о себе: {данные['about']}")

    if данные["interests"]:
        части.append(
            "Его интересы: " + ", ".join(данные["interests"]) + ". "
            "Учитывай их в примерах и объяснениях, когда это уместно."
        )

    стиль = STYLES.get(данные["style"], STYLES[DEFAULT_STYLE])
    if данные["style"] != DEFAULT_STYLE or части:
        части.append(стиль["prompt"])

    return "\n".join(части)
