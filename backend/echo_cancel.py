"""
Эхоподавление: Scott перестаёт слышать себя.

ЗАЧЕМ. Микрофон слышит колонки, и собственный ответ возвращается к Scott как
новая фраза. На живой проверке это выглядело так: он произнёс ответ, а
следующей строкой в логе появилось «Мимо: "Попробую открыть Google Chrome"» —
он распознал сам себя. Пока в ответе не звучит его имя, дело кончается лишней
работой распознавателя, но стоит сказать «Скотт» — и разговор с самим собой
пойдёт по кругу.

Обходились до сих пор двумя костылями: на время ответа микрофон почти глухой, а
перебить Scott можно только если говорить громче колонок и короткой фразой,
которая вдобавок сверяется с текстом ответа. Работает, но человеку приходится
повышать голос — а это ровно то, чего от домашнего помощника не ждут.

ПОЧЕМУ СВОЁ. Готовых библиотек под Windows не нашлось: speexdsp не собирается
без компилятора и самой библиотеки, webrtc-audio-processing падает на сборке
колеса. Зато у нас есть то, чего нет у них: Scott сам синтезирует ответ и
точно знает, что звучит в колонках. Опорный сигнал не надо перехватывать с
устройства вывода — он у нас на руках.

КАК УСТРОЕНО. Две ступени, и первая важнее второй.

Первая — задержка. Между «отдали звук на воспроизведение» и «микрофон это
услышал» проходит от сотни до нескольких сотен миллисекунд: буферы драйвера,
колонки, воздух. Величина эта своя на каждой машине, и угадать её нельзя —
она измеряется по взаимной корреляции: где опорный сигнал лучше всего
совпадает с записанным, там и задержка.

Вторая — вычитание. Эхо приходит не таким, каким ушло: колонки и комната
меняют его. Адаптивный фильтр (нормализованный метод наименьших квадратов)
подбирает поправку на ходу и вычитает предсказанное эхо из записи.

ЧЕГО ЭТО НЕ ДЕЛАЕТ. Идеальной тишины не будет: остаток эха всегда есть, и
порог громкости никуда не денется — он лишь опускается до разумного. И если
человек говорит ровно тогда же, когда Scott, разобрать обе речи всё равно
трудно: подавление убирает эхо, а не разделяет голоса.
"""

from __future__ import annotations

import numpy as np

# Сколько отсчётов охватывает адаптивный фильтр.
#
# Это длина «хвоста» комнаты, который он способен учесть: 512 отсчётов при 16
# кГц — тридцать две миллисекунды. Замер показал, что этого и надо: отражения
# от стен приходят через десять-тридцать миллисекунд, и фильтр на шестнадцать
# миллисекунд их не доставал — подавление падало с тридцати семи децибел до
# двадцати шести.
#
# Больше значит дороже: работа растёт линейно, а считать приходится на каждый
# блок в реальном времени. Основную задержку снимает не фильтр, а выравнивание
# по корреляции.
FILTER_TAPS = 512

# Насколько резво фильтр подстраивается.
#
# Больше — быстрее сходится, но и легче расходится на громких местах. Половина
# — обычный выбор для этого метода: сходимость за несколько десятков блоков,
# устойчивость на речи.
STEP_SIZE = 0.5

# Защита от деления на ноль там, где опорный сигнал молчит.
EPSILON = 1e-8

# Во сколько раз запись должна превысить ожидаемое эхо, чтобы счесть, что
# говорят оба сразу.
#
# Признак взят не из подавления, а из громкости, и это важно. Первая версия
# сравнивала остаток с записью — «остаётся почти столько же, значит говорит
# человек», — но пока фильтр не обучен, остаток и равен записи по определению.
# Защита срабатывала с четвёртого блока и замораживала обучение навсегда: из
# ста двадцати блоков пропускалось сто, и вместо десяти децибел подавления
# выходило ноль целых четыре десятых.
#
# Громкость же не зависит от того, обучен фильтр или нет. Ожидаемое эхо
# считается по опорному сигналу и оценке усиления; вдвое громче — значит, в
# записи есть кто-то ещё.
DOUBLE_TALK_EXCESS = 2.0

# Сколько блоков фильтр учится, прежде чем включится защита.
#
# Полсекунды при блоке в тридцать миллисекунд: за это время набирается оценка
# усиления, без которой сравнивать не с чем.
BLOCKS_BEFORE_GUARD = 16

# Насколько далеко искать задержку.
#
# Полсекунды, и это не запас на всякий случай. На живой машине — обычные
# колонки, обычный микрофон — задержка оказалась 375 миллисекунд при пределе в
# 400: почти у самого края. Значит на технике помедленнее она вышла бы за
# предел, и подавление молча перестало бы работать, упершись в потолок поиска.
MAX_DELAY_SECONDS = 0.55

# Сколько звука брать для замера задержки. Короткий кусок даёт случайный
# максимум корреляции; полсекунды речи хватает, чтобы он был настоящим.
DELAY_PROBE_SECONDS = 0.5


def estimate_delay(recorded: np.ndarray, reference: np.ndarray,
                   sample_rate: int = 16000) -> int:
    """
    На сколько отсчётов эхо отстаёт от опорного сигнала.

    Ищется по взаимной корреляции: где опорный сигнал лучше всего совпадает с
    записанным, там и задержка. Величина своя на каждой машине — буферы
    драйвера, колонки, расстояние до микрофона, — и угадать её нельзя.

    Возвращает ноль, если совпадения не нашлось: лучше не двигать сигнал
    вовсе, чем сдвинуть наугад.
    """
    if recorded.size == 0 or reference.size == 0:
        return 0

    предел = int(MAX_DELAY_SECONDS * sample_rate)
    проба = int(DELAY_PROBE_SECONDS * sample_rate)

    # Ищем опорный сигнал ВНУТРИ записи, а не наоборот.
    #
    # При задержке D запись отстаёт: recorded[D:] соответствует reference[:-D].
    # Первая версия искала кусок записи в опорном сигнале — то есть в обратную
    # сторону, — и находила случайный максимум: на замерах ошибка выходила от
    # двадцати до ста восьмидесяти миллисекунд при фильтре длиной шестнадцать.
    образец = reference[:проба]
    окно = recorded[:проба + предел]

    if образец.size < 64 or окно.size < образец.size:
        return 0

    # Убираем постоянную составляющую: она сдвигает максимум туда, где сигнала
    # больше, а не туда, где он похож.
    образец = образец - образец.mean()
    окно = окно - окно.mean()

    if np.sqrt((образец ** 2).mean()) < 1e-5:
        return 0

    совпадение = np.correlate(окно, образец, mode="valid")
    if совпадение.size == 0:
        return 0

    сдвиг = int(np.argmax(совпадение))
    return max(0, min(сдвиг, предел))


class EchoCanceller:
    """
    Вычитает из записи то, что Scott произносит сам.

    Живёт между микрофоном и распознаванием: получает блок записи и тот же
    отрезок опорного сигнала, возвращает блок без эха.

    Состояние копится между блоками — в этом весь смысл адаптивного фильтра:
    он подстраивается под комнату по ходу разговора, а не начинает заново
    каждые тридцать миллисекунд.
    """

    def __init__(self, taps: int = FILTER_TAPS, step: float = STEP_SIZE):
        self.taps = taps
        self.step = step

        # Коэффициенты фильтра: чем он стал к этой минуте.
        self.weights = np.zeros(taps, dtype=np.float32)

        # Хвост предыдущего опорного блока: фильтру нужна предыстория, иначе
        # первые отсчёты каждого блока остаются без неё.
        self._tail = np.zeros(taps - 1, dtype=np.float32)

        self.blocks = 0

        # Сколько блоков пропущено из-за двойного разговора — по ним видно,
        # часто ли человек говорит поверх Scott.
        self.skipped = 0

        # Во сколько раз эхо тише того, что ушло в колонки.
        #
        # Величина своя на каждой машине: зависит от громкости, расстояния до
        # микрофона и его чувствительности. Оценивается на ходу по блокам, где
        # говорит только Scott.
        self.echo_gain = 0.0

    def reset(self) -> None:
        """
        Забыть настройку.

        Нужно между ответами: за паузу могли поменять громкость, переставить
        колонки или сменить устройство вывода, и прежние коэффициенты станут
        не улучшать, а портить.
        """
        self.weights = np.zeros(self.taps, dtype=np.float32)
        self._tail = np.zeros(self.taps - 1, dtype=np.float32)
        self.blocks = 0
        self.skipped = 0
        self.echo_gain = 0.0

    def process(self, recorded: np.ndarray, reference: np.ndarray) -> np.ndarray:
        """
        Убрать эхо из блока записи.

        `recorded` — что услышал микрофон, `reference` — что в это время
        звучало в колонках, уже выровненное по задержке. Длины должны
        совпадать; если опорного сигнала не хватает, он дополняется тишиной —
        ответ Scott кончился раньше блока.
        """
        recorded = np.asarray(recorded, dtype=np.float32).ravel()

        if recorded.size == 0:
            return recorded

        reference = np.asarray(reference, dtype=np.float32).ravel()

        if reference.size < recorded.size:
            reference = np.pad(reference, (0, recorded.size - reference.size))
        else:
            reference = reference[:recorded.size]

        # Опорный сигнал молчит — вычитать нечего, и трогать фильтр незачем:
        # на тишине он только расшатается.
        if np.abs(reference).max() < 1e-5:
            self._tail = np.concatenate([self._tail, reference])[-(self.taps - 1):]
            return recorded

        # Предыстория плюс нынешний блок: из этого набираются окна для фильтра.
        поток = np.concatenate([self._tail, reference])
        очищенный = np.empty_like(recorded)

        # Говорят оба сразу?
        #
        # Сравниваются громкости: сколько эха ожидается по опорному сигналу и
        # сколько звука пришло на самом деле. Признак не зависит от того,
        # обучен ли фильтр, — в этом всё дело. Прежняя версия смотрела на
        # подавление и глушила обучение с четвёртого блока, так что фильтр не
        # успевал научиться ничему.
        громко_пришло = float(np.sqrt((recorded ** 2).mean()))
        громко_ушло = float(np.sqrt((reference ** 2).mean()))

        созрел = self.blocks >= BLOCKS_BEFORE_GUARD and self.echo_gain > 0
        ожидалось = self.echo_gain * громко_ушло

        двойной_разговор = (созрел and ожидалось > 1e-6
                            and громко_пришло > ожидалось * DOUBLE_TALK_EXCESS)

        # Первый проход — вычитание. Оно делается всегда: даже когда учиться
        # нельзя, эхо вычитать нужно.
        for i in range(recorded.size):
            окно = поток[i:i + self.taps][::-1]
            очищенный[i] = float(recorded[i]) - float(np.dot(self.weights, окно))

        if двойной_разговор:
            self.skipped += 1
            self._tail = поток[-(self.taps - 1):]
            self.blocks += 1
            return очищенный

        # Второй проход — с обучением.
        for i in range(recorded.size):
            окно = поток[i:i + self.taps][::-1]

            предсказанное = float(np.dot(self.weights, окно))
            остаток = float(recorded[i]) - предсказанное
            очищенный[i] = остаток

            # Шаг нормализуется мощностью окна: иначе громкая речь толкала бы
            # коэффициенты сильнее тихой, и фильтр расходился бы на всплесках.
            мощность = float(np.dot(окно, окно)) + EPSILON
            self.weights += (self.step * остаток / мощность) * окно

        # Оценка усиления обновляется только здесь — на блоках, где говорит
        # один Scott. Обновлять её во время двойного разговора значило бы
        # учить защиту считать чужой голос эхом.
        if громко_ушло > 1e-5:
            сейчас = громко_пришло / громко_ушло
            self.echo_gain = (0.8 * self.echo_gain + 0.2 * сейчас
                              if self.echo_gain else сейчас)

        self._tail = поток[-(self.taps - 1):]
        self.blocks += 1

        return очищенный


def suppression_db(before: np.ndarray, after: np.ndarray) -> float:
    """
    Насколько тише стало, в децибелах.

    Мера пользы: во сколько раз упала громкость эха. Единица измерения
    привычная для звука, и по ней сразу видно, стоила ли работа затрат.
    """
    было = float(np.sqrt((np.asarray(before, dtype=np.float64) ** 2).mean()))
    стало = float(np.sqrt((np.asarray(after, dtype=np.float64) ** 2).mean()))

    if было < 1e-12:
        return 0.0
    if стало < 1e-12:
        return 99.0

    return float(20 * np.log10(было / стало))
