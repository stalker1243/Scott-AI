using ScottAI.Mobile.Services;

namespace ScottAI.Mobile.Tests;

/// <summary>
/// Адрес компьютера человек переписывает с чужого экрана.
///
/// Он вводит то, что видит — «192.168.1.5», — и ничего сверх этого. Схему и
/// порт дописывает приложение: объяснять, почему «не подключается», дороже,
/// чем дописать за него два раза по семь символов.
/// </summary>
public class AddressTests
{
    [Theory]
    [InlineData("192.168.1.5", "http://192.168.1.5:8000")]
    [InlineData("  192.168.1.5  ", "http://192.168.1.5:8000")]
    [InlineData("192.168.1.5:8000", "http://192.168.1.5:8000")]
    [InlineData("http://192.168.1.5", "http://192.168.1.5:8000")]
    [InlineData("http://192.168.1.5:9000/", "http://192.168.1.5:9000")]
    public void Адрес_дополняется_до_рабочего(string введено, string ожидается)
    {
        Assert.Equal(ожидается, ScottClient.Normalize(введено));
    }

    [Theory]
    [InlineData("")]
    [InlineData("   ")]
    public void Пустой_адрес_остаётся_пустым(string введено)
    {
        // Пустой адрес — это «ещё не привязан», и превращать его в
        // «http://:8000» значило бы стучаться в никуда и получать невнятную
        // ошибку связи вместо понятной просьбы вписать адрес.
        Assert.Equal("", ScottClient.Normalize(введено));
    }

    [Fact]
    public void Свой_порт_сохраняется()
    {
        // Порт по умолчанию 8000, но Scott можно запустить на другом — и тогда
        // молча подменить его было бы хуже, чем не дописывать вовсе.
        Assert.Equal("http://192.168.1.5:8123", ScottClient.Normalize("192.168.1.5:8123"));
    }
}
